"""Generate docs/mbar/VALIDATION_TABLES.md from the stored results (no number is typed by hand).

Run:  python experiments/mbar/bench/make_tables.py          (rewrites the file)
      python experiments/mbar/bench/make_tables.py --check  (fails if the file is out of date)
"""
import ast
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "results")
OUT = os.path.join(HERE, "..", "..", "..", "docs", "mbar", "VALIDATION_TABLES.md")


def load(name):
    p = os.path.join(RES, name)
    return json.load(open(p)) if os.path.exists(p) else None


def fmt(x, d=3):
    return "—" if x is None else (f"{x:.{d}f}" if isinstance(x, float) else str(x))


def regime_name(r):
    if r["kind"] == "discrete":
        return f"discrete 4-state, overlap {r['overlap']}, n = {r['n']}"
    return f"harmonic K = {r['K']}, spacing {r['spread']}, n = {r['n']}"


def main():
    L = ["# Division 9 — validation tables (generated)", "",
         "*Generated by `experiments/mbar/bench/make_tables.py` from `experiments/mbar/results/`; do not edit.*", ""]
    c_first = load("certificates_coverage.json")
    c = load("certificates_coverage_v3.json") or c_first        # v3: the final code (after the review)
    if c:
        L += ["## T1. Confidence statements for `f_{K−1} − f_0`: coverage, finite intervals, median width",
              f"*{c['trials']} repetitions per regime (BOOT: 40); nominal error 0.05; `n` samples per state.  "
              "LR8/LR2: likelihood-ratio region with 8/2 batches; C1, C2: handoff certificates; ASY: `±1.96·se`; "
              "BOOT: percentile bootstrap.  Cells: coverage / finite of trials / median width.*", "",
              "| regime | MBAR RMSE | LR8 | LR2 | C1 | C2 | ASY | BOOT | LR8/ASY | joint LR8 |", "|---|---|---|---|---|---|---|---|---|---|"]
        for r in c["regimes"]:
            m = r["methods"]

            def cell(k):
                v = m.get(k)
                if v is None:
                    return "—"
                return f"{v['coverage']:.3f} / {v['finite']} / {fmt(v['median_width'])}"
            ratio = m["LR8"]["median_width"] / m["ASY"]["median_width"]
            L.append(f"| {regime_name(r['regime'])} | {r['mbar_rmse']:.4f} | {cell('LR8')} | {cell('LR2')} | {cell('C1')} | "
                     f"{cell('C2')} | {cell('ASY')} | {cell('BOOT')} | {ratio:.2f} | {fmt(m['LR8']['joint_coverage'])} |")
        L += ["", "Median plug-in regret `ρ` of LR8 and median time per region (seconds):", "",
              "| regime | regret | time LR8 | time C2 | time ASY |", "|---|---|---|---|---|"]
        for r in c["regimes"]:
            m = r["methods"]
            L.append(f"| {regime_name(r['regime'])} | {fmt(m['LR8']['median_regret'], 2)} | {m['LR8']['median_time']:.3f} | "
                     f"{m['C2']['median_time']:.3f} | {m['ASY']['median_time']:.4f} |")
        L += ["", "This table is from the run with the final code (`certificates_coverage_v3.json`) when that file exists.  "
              "Earlier runs with the same seeds: `certificates_coverage.json` (first code), `certificates_coverage_v2.json` "
              "(after the two corrections of the interval code, `DEAD_ENDS.md` E7)."]
        for name, other in (("first code", c_first), ("after E7", load("certificates_coverage_v2.json"))):
            if other and other is not c:
                diffs = []
                for r1, r2 in zip(c["regimes"], other["regimes"]):
                    for k in ("LR8", "LR2", "C1", "C2", "ASY"):
                        a1, a2 = r1["methods"][k], r2["methods"][k]
                        w1, w2 = a1["median_width"] or 0.0, a2["median_width"] or 0.0
                        diffs.append(max(abs(a1["coverage"] - a2["coverage"]), abs(a1["finite"] - a2["finite"]),
                                         abs(w1 - w2) / max(w1, 1e-300) if w1 else 0.0))
                L += [f"Against the run '{name}': largest change of coverage, of the finite count, or relative change of the "
                      f"median width, over all regimes and the methods LR8, LR2, C1, C2, ASY: {max(diffs):.1e}."]
        L.append("")
    for fname, title in (("allocation_benchmark_2000.json", "T2. Allocation: mean-square error relative to equal counts, 2000 replicates"),
                         ("allocation_benchmark_costpilot2.json", "T3. Cost-heterogeneous systems with the post hoc pilot variants, 2000 replicates"),
                         ("allocation_benchmark.json", "T4. Allocation: first run, 400 replicates (kept for the record)")):
        a = load(fname)
        if fname == "allocation_benchmark_costpilot2.json" and a is None:
            a = load("allocation_benchmark_costpilot.json")
        if not a:
            continue
        meths = [k for k in ("EQUALCOST", "PILOT2", "PILOT2C", "PILOT2CE", "PILOT4", "NEYMAN1", "RESIST", "ORACLE")
                 if k in a["systems"][0]["methods"]]
        L += [f"## {title}",
              f"*Pilot fraction {a['pilot_fraction']}; budget = 3000 × mean cost; every method ends with MBAR on all its samples.  "
              "Cells: MSE ratio to UNIFORM [bootstrap 95 % interval].  'predicted' = population variance ratio of the "
              "oracle design (uses ground truth).  All ratios of a row share one UNIFORM estimate.*", "",
              "| system | predicted oracle | " + " | ".join(meths) + " | failed |", "|---|---|" + "---|" * (len(meths) + 1)]
        for s in a["systems"]:
            row = [s["name"], f"{s['population']['predicted_ratio_oracle_vs_uniform']:.3f}"]
            for k in meths:
                d = s["methods"][k]
                row.append(f"{d['mse_ratio_vs_uniform']:.3f} [{d['mse_ratio_ci95'][0]:.2f}, {d['mse_ratio_ci95'][1]:.2f}]")
            row.append(str(s["failed"]))
            L.append("| " + " | ".join(row) + " |")
        L += ["", "Allocations (mean final counts) and overhead:", "",
              "| system | costs | oracle design | PILOT2 mean counts | certified efficiency bound of uniform | "
              "median allocation time (s) | pilot fallbacks | UNIFORM RMSE | PILOT2 RMSE | PILOT2 bias |", "|---|---|---|---|---|---|---|---|---|---|"]
        for s in a["systems"]:
            p = s["methods"]["PILOT2"]
            L.append(f"| {s['name']} | {s['cost']} | {s['population']['oracle_allocation']} | {p['mean_counts']} | "
                     f"{s['population']['efficiency_lower_bound_of_uniform']:.3f} | {p['median_alloc_time']:.3f} | {p['fallbacks']} | "
                     f"{s['methods']['UNIFORM']['rmse']:.4f} | {p['rmse']:.4f} | {p['bias']:+.4f} |")
        L.append("")
    plog = os.path.join(RES, "robustness.log")
    if os.path.exists(plog):
        def read_rows(path):
            out = {"A": [], "B": [], "C": []}
            if os.path.exists(path):
                for line in open(path):
                    if line[:2] in ("A ", "B ", "C "):
                        out[line[0]].append(ast.literal_eval(line[2:].strip()))
            return out
        first = read_rows(plog)
        rows = {k: list(v) for k, v in first.items()}
        notes = []
        for part, fname in (("A", "robustness_final_AB.log"), ("B", "robustness_final_AB.log"), ("C", "robustness_final_C.log")):
            fin = read_rows(os.path.join(RES, fname))[part]
            if fin and len(fin) == len(first[part]):
                rows[part] = fin
                notes.append(part)
        L += ["*Robustness tables T5-T7: parts " + (", ".join(sorted(set(notes))) or "none") + " are from the rerun with the final "
              "code (same seeds); the first run is kept in `results/robustness.log`.*", ""]
        if rows["A"]:
            L += ["## T5. Experiment A: every round, adaptive allocation, halting on the interval width",
                  "*12 rounds of 400 samples; allocation of each round from the plug-in design of the earlier rounds; "
                  "region recomputed every round; halt when the interval of the contrast is below the target width.*", "",
                  "| overlap | trials | target width | truth excluded at any round | halted | median halting round | coverage at halt | "
                  "median final width | mean final counts |", "|---|---|---|---|---|---|---|---|---|"]
            for d in rows["A"]:
                L.append(f"| {d['overlap']} | {d['trials']} | {d['target_width']} | {d['ever_excluded_truth']:.3f} | {d['halted']} | "
                         f"{fmt(d['median_halt_round'], 1)} | {fmt(d['coverage_at_halt'])} | {d['median_final_width']:.3f} | {d['mean_final_counts']} |")
            L.append("")
        if rows["B"]:
            L += ["## T6. Experiment B: model check against trapped samplers (double well, five umbrellas)",
                  "*`equilibrium`: exact sampling; `one_trapped`: the central umbrella confined to the left well; "
                  "`all_trapped`: every umbrella confined to the left well.  `n` samples per state.*", "",
                  "| scenario | n | trials | model check rejects | median log e-value | MBAR RMSE (end to end) | mean error of f_2 − f_0 | "
                  "LR region contains truth | ASY covers (ends) | ASY covers (f_2 − f_0) |", "|---|---|---|---|---|---|---|---|---|---|"]
            for d in rows["B"]:
                L.append(f"| {d['scenario']} | {d['n']} | {d['trials']} | {d['reject_rate']:.3f} | {d['median_logE']:.1f} | "
                         f"{d['mbar_rmse_end_to_end']:.3f} | {d['mbar_mean_error_state2']:+.3f} | {fmt(d['lr_region_contains_truth'])} | "
                         f"{d['asymptotic_covers_end_to_end']:.3f} | {d['asymptotic_covers_state2']:.3f} |")
            L.append("")
        if rows["C"]:
            L += ["## T7. Experiment C: correlated samples (stationary AR(1) samplers, five harmonic states, 20000 steps each)",
                  "*`naive`: all steps as if independent; `iact`: every `(1+φ)/(1−φ)`-th step; `certified`: stride with remaining "
                  "correlation `≤ 0.01`; `estimated`: stride from the estimated statistical inefficiency of the own-state energy.*", "",
                  "| φ | treatment | trials | median samples kept | LR coverage | LR joint | LR median width | ASY coverage | ASY median width |",
                  "|---|---|---|---|---|---|---|---|---|"]
            for d in rows["C"]:
                L.append(f"| {d['phi']} | {d['mode']} | {d['trials']} | {d['median_kept']:.0f} | {fmt(d['lr_coverage'])} | {fmt(d['lr_joint'])} | "
                         f"{d['lr_median_width']:.3f} | {fmt(d['asy_coverage'])} | {d['asy_median_width']:.3f} |")
            L.append("")
    u = load("public_umbrella.json")
    if u:
        L += ["## T8. Public umbrella-sampling data (26 umbrellas; no ground truth; development evidence)",
              f"*Estimated statistical inefficiencies: min {u['statistical_inefficiency']['min']:.1f}, median "
              f"{u['statistical_inefficiency']['median']:.1f}, max {u['statistical_inefficiency']['max']:.1f}.  Free energies in units of kT.*", "",
              "| treatment | samples | max diff. to PyMBAR | region | regret | pair | estimate | asymptotic se | LR interval (all 26 states) | "
              "width / asymptotic | sub-ladder states | sub-ladder interval | width / asymptotic | model check log e |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for t in u["treatments"]:
            for r in t["pairs"]:
                L.append(f"| {t['treatment']} | {t['samples']} | {t['max_abs_difference_to_pymbar']:.1e} | {t['region_status']} | "
                         f"{fmt(t['regret'], 1)} | {r['pair']} | {r['estimate']:.3f} | {r['asymptotic_se']:.3f} | "
                         f"[{r['lr_interval'][0]:.2f}, {r['lr_interval'][1]:.2f}] | {r['lr_width_over_asymptotic_width']:.2f} | "
                         f"{r.get('sub_ladder_states', '—')} | [{r['sub_ladder_interval'][0]:.2f}, {r['sub_ladder_interval'][1]:.2f}] | "
                         f"{r['sub_ladder_width_over_asymptotic_width']:.2f} | {t['model_check_logE']:.1f} |")
        d = u["design_diagnostic"]
        L += ["", f"Design diagnostic (plug-in estimates, not certificates) for `{d['target']}`: estimate {d['estimate']:.3f}; "
              f"standard error at the actual allocation {d['plugin_se_actual_allocation']:.3f}, at the plug-in optimum "
              f"{d['plugin_se_optimal_allocation']:.3f} (variance ratio {d['plugin_variance_ratio_optimal_over_actual']:.3f}); "
              f"efficiency bound of the actual allocation {d['plugin_efficiency_lower_bound_of_actual']:.3f}; umbrellas carrying the "
              "plug-in optimum (centre in degrees, fraction): "
              + ", ".join(f"{x['centre']:.0f}: {x['fraction']:.3f}" for x in d["umbrellas_with_most_optimal_weight"]) + ".", ""]
    lb = load("lower_bounds_and_chains.json")
    if lb:
        s, a, cc = lb["submodel"], lb["adaptive"], lb["correlated"]
        L += ["## T9. Exact checks of the lower bounds and of the correlated-sampling statements", "",
              f"* least-favourable submodel (300 random models): exact divergence / ((16/9)τ²) ≤ {s['kl_ratio']:.4f}; exact separation / "
              f"(τ√(V/N)) in [{s['sep_ratio_min']:.4f}, {s['sep_ratio_max']:.4f}];",
              f"* adaptive bound: information accumulated by any allocation / (B·max_k Var_k(h°)/a_k) ≤ {a['max_information_ratio']:.6f};",
              f"* MBAR's correlated variance: {cc['convexity_violations_of_mbar_variance']} convexity violations in {cc['segments']} segments, "
              f"worst relative violation {cc['worst_relative_violation']:.4f};",
              f"* optimally weighted value `W`: largest convexity defect {cc['max_convexity_defect_of_W']:.2e}, largest `(W − V_corr)/V_corr` "
              f"{cc['max_excess_of_W_over_Vcorr']:.2e};",
              f"* scalar inefficiency model: relative error of `V_corr(s) = V(s/g)` {cc['scalar_model_max_relative_error']:.1e}.", ""]
    sy = load("synthesis_checks.json")
    if sy:
        L += ["## T10. Exact checks of the synthesis statements", "",
              f"* path bound: max `V/bound` {sy['S1']['max_V_over_path_bound']:.4f}; max `V*/length²` {sy['S1']['max_Vopt_over_length_bound']:.4f};",
              "* tempering ladders on the cube (`V_uniform` against `0.2716·K′²`): "
              + "; ".join(f"n={r['n']} u={r['u']} K′={r['ladder_states'] - 1}: {r['V_uniform']:.1f} vs {r['class_bound']:.1f}" for r in sy["S2"][::4]) + ";",
              "* envelope-ratio instance: " + "; ".join(
                  f"Γ={r['Gamma']:.0f}: reference-only {r['V_average_reference_only']:.2f}, target {r['V_average_target_only']:.3f}, "
                  f"free energy reference-only {r['V_free_energy_reference_only']:.1f}, ladder {r['V_free_energy_optimal_ladder']:.2f}" for r in sy["S3"]) + ";",
              f"* bridge instance: `V(e_m)` = {sy['S4']['V_bridge_only']:.3f} = `V*` = {sy['S4']['V_optimal']:.3f}; efficiency of uniform "
              f"{sy['S4']['uniform_efficiency']:.3f}.", ""]
    text = "\n".join(L) + "\n"
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT).read() == text
        print("tables up to date" if ok else "TABLES OUT OF DATE")
        sys.exit(0 if ok else 1)
    open(OUT, "w").write(text)
    print("written", os.path.relpath(OUT), len(L), "lines")


if __name__ == "__main__":
    main()
