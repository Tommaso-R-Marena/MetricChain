#!/usr/bin/env python3
"""Mutation testing of the falsification harness.

A test that cannot fail proves nothing.  Each mutation below is a small textual change to a scratch
COPY of `experiments/falsify_conjectures.py` (the repository file is never modified) that makes one
tested claim false, or breaks the test's own modelling of the claim; the affected test is then run
in quick mode.  A mutation is *caught* when the harness reports a misbehaving test (exit code 1)
**and no test of the mutant ended with an exception**: a mutant that crashes has refuted nothing.

Exactly one mutation is expected to pass: `DEAD.5 M2` restricts the search for a counterexample to
product references, where none exists, so the test must fall back to its explicit two-site
counterexample and still behave as documented.

Before the first mutation of a test is run, the UNMUTATED harness is run on the same selection in the
same mode (once per selection): a mutation of a test that misbehaves without any mutation would be
"caught" for the wrong reason, so such a baseline failure fails the run.

The run fails (exit code 1) if a mutation is not caught, if the expected pass does not pass, if a
baseline run misbehaves, or if a mutation pattern no longer occurs in the harness (the mutation list
is then stale and must be updated together with the test).

Usage:
    python3 experiments/mutation_tests.py            # all groups
    python3 experiments/mutation_tests.py X1 II4     # selected groups
"""
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "falsify_conjectures.py")
base = open(SRC).read()
TMP = tempfile.mkdtemp(prefix="metricchain-mutants-")
EXPECTED_PASS = ("DEAD.5 M2",)
RESULTS = dict(caught=0, expected_pass=0, bad=0)


BASELINE = {}


def baseline_ok(only, extra):
    """The unmutated harness must behave as expected on this selection, in this mode (cached)."""
    key = (only, tuple(extra))
    if key not in BASELINE:
        out = subprocess.run([sys.executable, SRC, "--only", only, *extra], capture_output=True, text=True)
        BASELINE[key] = out.returncode == 0
        if out.returncode != 0:
            print(f"!! BASELINE FAILS for --only {only!r} {' '.join(extra)}: the unmutated harness misbehaves, "
                  f"so no mutation of this selection can count as caught")
            print(out.stdout[-1200:])
    return BASELINE[key]


def run(label, edits, only, extra=("--quick",)):
    if not baseline_ok(only, extra):
        print(f"[{'NOT AS EXPECTED':>15}] {label}\n                  baseline of --only {only!r} misbehaves")
        RESULTS["bad"] += 1
        return
    s = base
    for old, new in edits:
        if s.count(old) < 1:
            print(f"!! {label}: STALE MUTATION, pattern not found: {old[:70]!r}")
            RESULTS["bad"] += 1
            return
        s = s.replace(old, new)
    path = os.path.join(TMP, "mutant.py")
    with open(path, "w") as fh:
        fh.write(s)
    out = subprocess.run([sys.executable, path, "--only", only, *extra], capture_output=True, text=True)
    verdict = out.stdout.strip().splitlines()[-1] if out.stdout.strip() else "(no output)"
    want_pass = label.startswith(EXPECTED_PASS)
    # "caught" means that the harness itself ran to its end and reported a counterexample (or a documented refutation that
    # disappeared).  A mutant that raises an exception inside a test (status ERROR), or that does not run at all, has refuted
    # nothing: the mutation is then badly written and is reported as such.
    crashed = any(line.startswith("[" + "ERROR".rjust(24) + "]") for line in out.stdout.splitlines()) \
        or (out.returncode != 0 and "TEST(S) MISBEHAVED" not in verdict)
    ok = ((out.returncode == 0) if want_pass else (out.returncode == 1)) and not crashed
    status = ("expected pass" if want_pass else "caught") if ok else ("NOT AS EXPECTED (the mutant crashed)" if crashed else "NOT AS EXPECTED")
    print(f"[{status:>15}] {label}\n                  exit={out.returncode}  {verdict}")
    if not ok:
        RESULTS["bad"] += 1
        print(out.stdout[-1200:])
        print(out.stderr[-600:])
    elif want_pass:
        RESULTS["expected_pass"] += 1
    else:
        RESULTS["caught"] += 1


