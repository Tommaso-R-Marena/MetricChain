"""GEOMETRY-REQ-0001, item 1: the scheme  {P in Sym(6) : rank P <= 3, e^T P e = |e|^2 on the
constrained edge vectors}  for two-state ensembles with n = 9, 10, 11, 12 atoms.

Run from the repository root:

    python experiments/eng/geometry_req1/item1_pencil.py            # all witnesses, about 9 min
    python experiments/eng/geometry_req1/item1_pencil.py --quick    # main witness only, about 1 min

Output: experiments/eng/geometry_req1/results/item1_pencil.json

What is computed (all coordinates unweighted, see enslib.linear_system for why the weights do not
matter), for each witness and each n:

 1. the rank of the 2n-3 linear equations on Sym(6) (exact, over Q), a basis of the pencil
    L = Q E_1 + N(z) (dimension v = 22 - rank), with homogenising coordinate h = x_0 + x_1;
 2. the quadrics of rank 2 in N(z) (points at infinity of rank 2), exactly, by exhaustion;
 3. the 120 minors of order 4 of the pencil as quartic forms in v variables with integer
    coefficients (exact), the dimension over Q of their span (exact rank), and the Hilbert function
    d -> dim S_d / J_d of the ideal J they generate, for a few degrees, over Q in degree 4 and
    modulo primes above (Macaulay matrices; rank_p <= rank_Q, so HF_Q(d) <= HF_p(d));
 4. for n = 10: the certificate that J is, in adapted coordinates, the monomial ideal generated by
    all quartic monomials except seven - which proves that the affine scheme is exactly the two
    forced points, both reduced, and that the scheme at infinity is one point of rank 2 with its
    full first-order neighbourhood (multiplicity 5);
 5. for n = 11, 12: J_4 = (ideal of the two forced points)_4, i.e. exactly two reduced points and
    nothing at infinity;
 6. reducedness of the forced points by the tangent-space criterion (exact);
 7. (remark, outside the request) the quadrics of rank 2 in N(z) for one three-state ensemble with
    n = 15, 16, 17 atoms: they exist exactly as long as n <= 6K - 2.

Arithmetic: Python integers / fractions.Fraction; python-flint for exact ranks over Q
(fmpz_mat.rank) and for ranks modulo 61..64-bit primes (nmod_mat).  No floating point.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import enslib as el  # noqa: E402

try:
    import flint  # type: ignore
except Exception as exc:  # pragma: no cover
    raise SystemExit("this script needs python-flint (pip install python-flint): %s" % exc)

PRIMES = [2305843009213693951, 4611686018427387847, 9223372036854775783, 18446744073709551557]
PIN = "d84a43b"


def witnesses(quick):
    out = [("geometry_seed_0", "geometry", 0)]
    if not quick:
        out += [("geometry_seed_1", "geometry", 1), ("geometry_seed_2", "geometry", 2),
                ("geometry_seed_3", "geometry", 3), ("geometry_seed_4", "geometry", 4),
                ("eng_0", "eng", 0), ("eng_1", "eng", 1), ("eng_2", "eng", 2)]
    return out


def tangents_of(kind, index, n):
    if kind == "geometry":
        return el.geometry_witness_tangents(2, n, index)
    return el.eng_witness_tangents(2, n, index)


def rank_Q(rows):
    return int(flint.fmpz_mat(rows).rank()) if rows else 0


def rank_p(rows, p):
    return int(flint.nmod_mat([[x % p for x in r] for r in rows], p).rank()) if rows else 0


def hilbert_function_mod_p(polys, v, degrees, p):
    """dim S_d / J_d over F_p for the ideal generated by the quartics `polys`, d in degrees."""
    red = [{e: c % p for e, c in f.items()} for f in polys]
    # a basis of the degree-4 span keeps the Macaulay matrices small
    rows4 = el.dense_rows(red, v, 4)
    R, r4 = flint.nmod_mat(rows4, p).rref()
    mons4 = el.monomials(v, 4)
    Rl = R.tolist()
    basis = [{mons4[j]: int(c) for j, c in enumerate(Rl[i]) if int(c)} for i in range(r4)]
    out = {}
    for d in degrees:
        rows = el.dense_rows(el.macaulay_rows(basis, v, 4, d), v, d)
        out[d] = len(rows[0]) - int(flint.nmod_mat(rows, p).rank())
    return out


def poly_hash(polys, v):
    """SHA-256 of a canonical text serialisation of a list of integer polynomials."""
    h = hashlib.sha256()
    for f in polys:
        for e in el.monomials(v, 4):
            h.update(("%s:%d;" % (",".join(map(str, e)), f.get(e, 0))).encode())
        h.update(b"|")
    return h.hexdigest()


def unit(v, i):
    return tuple(1 if a == i else 0 for a in range(v))


def analyse(name, kind, index, n, hf_degrees, primes, store_basis):
    t0 = time.time()
    tans = tangents_of(kind, index, n)
    chains, z = el.ensemble(tans)
    res = {"witness": name, "n": n,
           "tangents": [[str(t) for t in row] for row in tans],
           "chain_constraints_exact": all(el.check_chain(c) for c in chains)}
    A, b = el.linear_system(z)
    fams = el.rank2_families_at_infinity(z)
    res["rank2_quadrics_in_N"] = [{"lambda_bonds": f["lambda_bonds"], "mu_bonds": f["mu_bonds"],
                                   "projective_dimension_of_family": f["dimension"]} for f in fams]
    first = []
    if n == 10:
        assert len(fams) == 1 and fams[0]["dimension"] == 0
        lam, mu = fams[0]["ann_lambda"][0], fams[0]["ann_mu"][0]
        Ninf = el.sym_outer(lam, mu)
        assert el.in_conic_space(Ninf, z) and el.rank_exact(Ninf) == 2
        first = [Ninf]
        res["point_at_infinity"] = {
            "description": "N_inf = lam mu^T + mu lam^T; lam (mu) is the normal of the affine "
                           "hyperplane of Q^6 through the first (last) six stacked atoms",
            "lambda": [str(x) for x in lam], "mu": [str(x) for x in mu],
            "in_N_exact": True, "rank": 2,
            "signature": "(1, 1): one positive, one negative eigenvalue (lam, mu real, independent)"}
    # every listed family really lies in N(z) (exact), whatever n
    for f in fams:
        for lam in f["ann_lambda"]:
            for mu in f["ann_mu"]:
                S = el.sym_outer(lam, mu)
                assert el.in_conic_space(S, z) and el.rank_exact(S) == 2
    mats, rank, dimN = el.pencil_basis(z, first=first)
    v = len(mats)
    res["linear_system"] = {"equations": len(A), "rank": rank, "dim_N": dimN,
                            "pencil_dimension_v": v, "affine_dimension": v - 1}
    dN, r22, r11 = el.forced_point_tangent_ranks(z)
    res["forced_points"] = {"satisfy_linear_system_exactly": True,
                            "tangent_map_rank_at_E1": r22, "tangent_map_rank_at_E2": r11,
                            "reduced": (r22 == dN and r11 == dN)}
    minors = el.all_4x4_minors(mats)
    polys = [f for _, f in minors]
    rows4 = el.dense_rows(polys, v, 4)
    nmon = len(rows4[0])
    rq = rank_Q(rows4)
    res["minors"] = {"count": len(polys), "quartic_monomials": nmon,
                     "span_rank_over_Q": rq, "HF_Q_degree_4": nmon - rq,
                     "span_rank_mod_p": {str(p): rank_p(rows4, p) for p in primes},
                     "max_coefficient_digits": max(len(str(abs(c))) for f in polys for c in f.values()),
                     "sha256_of_minors_in_this_basis": poly_hash(polys, v)}
    res["hilbert_function_mod_p"] = {str(p): {str(d): hv for d, hv in
                                              hilbert_function_mod_p(polys, v, hf_degrees, p).items()}
                                     for p in primes[:2]}
    # both forced points lie on the scheme: every minor vanishes at x = e_0 and x = e_1
    # (the value of a quartic form at the coordinate point e_i is its coefficient of x_i^4)
    res["minors_vanish_at_forced_points"] = all(
        f.get(tuple(4 if a == 0 else 0 for a in range(v)), 0) == 0
        and f.get(tuple(4 if a == 1 else 0 for a in range(v)), 0) == 0 for f in polys)

    if n == 10:
        # --- the certificate: in the coordinates of (E_1, E_2, N_inf, B_3, B_4) the 120 minors
        # have no term in the seven monomials below, and they span a space of dimension 63 = 70 - 7.
        excluded = [tuple(4 if a == i else 0 for a in range(v)) for i in (0, 1, 2)]
        excluded += [tuple((3 if a == 2 else 0) + (1 if a == j else 0) for a in range(v))
                     for j in (0, 1, 3, 4)]
        zero_cols = all(f.get(e, 0) == 0 for f in polys for e in excluded)
        # direct exact membership: h^3 x_2, h^3 x_3, h^3 x_4, h^2 x_0 x_1 lie in the Q-span
        hform = {unit(v, 0): 1, unit(v, 1): 1}
        h2 = el.pmul(hform, hform)
        h3 = el.pmul(h2, hform)
        targets = [el.pmul(h3, {unit(v, k): 1}) for k in (2, 3, 4)]
        targets.append(el.pmul(h2, {tuple(1 if a in (0, 1) else 0 for a in range(v)): 1}))
        rq_aug = rank_Q(rows4 + el.dense_rows(targets, v, 4))
        res["n10_certificate"] = {
            "coordinates": "P = x_0 E_1 + x_1 E_2 + x_2 N_inf + x_3 B_3 + x_4 B_4, h = x_0 + x_1",
            "excluded_monomials": ["x0^4", "x1^4", "x2^4", "x2^3*x0", "x2^3*x1", "x2^3*x3", "x2^3*x4"],
            "all_minors_have_zero_coefficient_on_excluded_monomials": zero_cols,
            "span_rank_over_Q": rq, "expected_rank": nmon - 7,
            "J4_is_the_span_of_the_63_other_quartic_monomials": bool(zero_cols and rq == nmon - 7),
            "targets": ["h^3*x2", "h^3*x3", "h^3*x4", "h^2*x0*x1"],
            "rank_over_Q_of_minors_plus_targets": rq_aug,
            "targets_in_Q_span_of_minors": rq_aug == rq,
            "affine_ideal": "(x2, x3, x4, x1^2 - x1) in Q[x1, x2, x3, x4] (x0 = 1 - x1): radical, "
                            "dimension 0, degree 2; points x = (1,0,0,0,0) = E_1 and (0,1,0,0,0) = E_2",
            "homogeneous_ideal_saturation": "(x0 x1, x0 x3, x0 x4, x1 x3, x1 x4, x3^2, x3 x4, x4^2, "
                                            "x0^2 x2, x1^2 x2) = I(E_1) ∩ I(E_2) ∩ I(N_inf)^2: "
                                            "degree 7 = 1 + 1 + 5",
        }
        if store_basis:
            res["n10_certificate"]["basis_matrices"] = {
                "B3": [[str(x) for x in row] for row in mats[3]],
                "B4": [[str(x) for x in row] for row in mats[4]],
                "N_inf": [[str(x) for x in row] for row in mats[2]]}
            res["chains"] = [[[str(c) for c in atom] for atom in ch] for ch in chains]
    if n in (11, 12):
        res["two_reduced_points_only"] = bool(rq == nmon - 2)
    res["seconds"] = round(time.time() - t0, 1)
    return res


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    args = ap.parse_args()
    out = {"request": "GEOMETRY-REQ-0001 item 1", "geometry_commit": PIN,
           "arithmetic": "exact integers / rationals; ranks over Q by FLINT fmpz_mat.rank; modular "
                         "ranks by FLINT nmod_mat", "primes": [str(p) for p in PRIMES],
           "python_flint": flint.__version__, "results": []}
    for name, kind, index in witnesses(args.quick):
        for n in (9, 10, 11, 12):
            main_w = (name == "geometry_seed_0")
            if n == 9:
                degs = [4, 5, 6, 7] if main_w else [4, 5, 6]
            else:
                degs = [4, 5, 6, 7, 8] if main_w else [4, 5, 6]
            r = analyse(name, kind, index, n, degs, PRIMES, store_basis=(main_w and n == 10))
            out["results"].append(r)
            ls = r["linear_system"]
            print(f"{name:16s} n={n:2d} rank={ls['rank']:2d} dimN={ls['dim_N']} "
                  f"rank_Q(minors)={r['minors']['span_rank_over_Q']:3d}/{r['minors']['quartic_monomials']:3d} "
                  f"HF_Q(4)={r['minors']['HF_Q_degree_4']:3d} "
                  f"HF_p={list(r['hilbert_function_mod_p'].values())[0]} "
                  f"rank2@inf={[(f['projective_dimension_of_family']) for f in r['rank2_quadrics_in_N']]} "
                  f"forced reduced={r['forced_points']['reduced']} [{r['seconds']}s]", flush=True)
            if n == 10:
                c = r["n10_certificate"]
                print(f"{'':16s}      n=10 certificate: zero columns {c['all_minors_have_zero_coefficient_on_excluded_monomials']}, "
                      f"rank {c['span_rank_over_Q']} = {c['expected_rank']}, targets in span {c['targets_in_Q_span_of_minors']}",
                      flush=True)
    if not args.quick:
        # Remark (outside the request): quadrics of rank 2 in N(z) exist for every K as long as two
        # windows of 3K consecutive stacked atoms overlapping in two atoms cover the chain, i.e.
        # for n <= 6K - 2.  Exact check for K = 3 and one witness (n = 15: two lines and five
        # isolated points; n = 16: one isolated point; n = 17: none).
        out["remark_rank2_quadrics_K3"] = []
        for n in (15, 16, 17):
            t0 = time.time()
            chains, z = el.ensemble(el.eng_witness_tangents(3, n, 0))
            fams = el.rank2_families_at_infinity(z)
            for f in fams:
                for la in f["ann_lambda"]:
                    for mu_ in f["ann_mu"]:
                        S = el.sym_outer(la, mu_)
                        assert el.in_conic_space(S, z) and el.rank_exact(S) == 2
            rec = {"K": 3, "n": n, "witness": "eng_0",
                   "families": [{"lambda_bonds": f["lambda_bonds"], "mu_bonds": f["mu_bonds"],
                                 "projective_dimension_of_family": f["dimension"]} for f in fams],
                   "seconds": round(time.time() - t0, 1)}
            out["remark_rank2_quadrics_K3"].append(rec)
            print(f"remark K=3 n={n}: rank-2 quadrics in N(z): "
                  f"{[(f['lambda_bonds'], f['mu_bonds'], f['dimension']) for f in fams]} [{rec['seconds']}s]",
                  flush=True)
    path = HERE / "results" / ("item1_pencil_quick.json" if args.quick else "item1_pencil.json")
    path.parent.mkdir(exist_ok=True)
    path.write_text(json.dumps(out, indent=1) + "\n")
    print("wrote", path.relative_to(HERE.parents[2]))


if __name__ == "__main__":
    main()
