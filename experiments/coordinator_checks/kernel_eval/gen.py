E2_COMMON = r'''
/-- `body b` for all `b < c` (evaluated for `b = c-1, …, 0`). -/
def allBelow (body : Nat → Bool) : Nat → Bool
  | 0 => true
  | b+1 =>
      match body b with
      | true => allBelow body b
      | false => false

/-- `Σ_{j < c} f j`. -/
def sumBelow (f : Nat → Nat) : Nat → Nat
  | 0 => 0
  | j+1 => Nat.add (f j) (sumBelow f j)

/-- `i * w + j`. -/
def ix (w i j : Nat) : Nat := Nat.add (Nat.mul i w) j

/-- `x ≤ r` and `y ≤ r`. -/
def le2 (x y r : Nat) : Bool :=
  match Nat.ble x r with
  | true => Nat.ble y r
  | false => false

/-- `c1 && c2 && c3`, left to right. -/
def and3 (c1 c2 c3 : Bool) : Bool :=
  match c1 with
  | false => false
  | true =>
    match c2 with
    | false => false
    | true => c3
'''

E2_CHECKER = r'''
/-! Checker E2.  Every table is ONE natural number; entry `t` is the 64-bit field at bits
`[64 t, 64 t + 64)` and holds `value + off` with `off = 2^62`, so all fields are nonnegative.
Row-major layouts: `hN[i k + a]`, `uN[i]`, `pN[i n + j]`, `mN[(i n + j) k + a]`,
`jN[((i n + j) k + a) k + b]` (diagonal blocks `i = j` are present and ignored).
`Lo = L + n^2 off`.  With the offsets the three conditions read
  (A) `u' + (n-1) off ≤ h' + Σ_{j≠i} m'`,
  (B) `2 p' + m' + m' ≤ J' + J' + 2 off`,
  (C) `Lo ≤ Σ u' + Σ p'`.
All loops are structural recursion on a `Nat` counter; all arithmetic is `Nat.add`, `Nat.mul`,
`Nat.ble`, `Nat.beq`, `Nat.shiftRight`, `Nat.mod` on literals. -/
namespace E2
''' + E2_COMMON + r'''
/-- Field `t` of the packed table `T` (flat read: shift the whole table, keep 64 bits).
`Nat.mod … 2^64` rather than `Nat.land … (2^64-1)`: same value, but the definition of `Nat.land`
in core depends on `propext`, which `#print axioms` would then report. -/
def fld (T t : Nat) : Nat := Nat.mod (Nat.shiftRight T (Nat.mul 64 t)) 18446744073709551616

def checkA (n k off hN uN mN : Nat) : Bool :=
  allBelow (fun i => allBelow (fun a =>
    Nat.ble (Nat.add (fld uN i) (Nat.mul (Nat.sub n 1) off))
      (Nat.add (fld hN (ix k i a))
        (sumBelow (fun j =>
          match Nat.beq j i with
          | true => 0
          | false => fld mN (ix k (ix n i j) a)) n))) k) n

/-- One cell of (B) for the unordered pair `j < i`: both orientations share the right-hand side. -/
def cellOK (n k off pN mN jN i j a b : Nat) : Bool :=
  le2
    (Nat.add (Nat.mul 2 (fld pN (ix n i j)))
      (Nat.add (fld mN (ix k (ix n i j) a)) (fld mN (ix k (ix n j i) b))))
    (Nat.add (Nat.mul 2 (fld pN (ix n j i)))
      (Nat.add (fld mN (ix k (ix n i j) a)) (fld mN (ix k (ix n j i) b))))
    (Nat.add (Nat.add (fld jN (ix k (ix k (ix n i j) a) b)) (fld jN (ix k (ix k (ix n j i) b) a)))
      (Nat.mul 2 off))

def checkB (n k off pN mN jN : Nat) : Bool :=
  allBelow (fun i => allBelow (fun j => allBelow (fun a => allBelow (fun b =>
    cellOK n k off pN mN jN i j a b) k) k) i) n

def checkC (n Lo uN pN : Nat) : Bool :=
  Nat.ble Lo
    (Nat.add (sumBelow (fun i => fld uN i) n)
      (sumBelow (fun i => sumBelow (fun j =>
        match Nat.beq j i with
        | true => 0
        | false => fld pN (ix n i j)) n) n))

/-- The leaf check on packed tables. -/
def leafCheck (n k off Lo hN uN pN mN jN : Nat) : Bool :=
  and3 (checkA n k off hN uN mN) (checkB n k off pN mN jN) (checkC n Lo uN pN)

end E2
'''

E2H_CHECKER = r'''
/-! Checker E2h.  Same packed tables as E2 (one natural number per table, 64-bit fields, entries
offset by `off = 2^62`, row-major layouts), but the big table `J` and the message table are read
HIERARCHICALLY: first the part of site `i` (width `64 n k^2` bits), then the block of the pair
`(i, j)` inside it (width `64 k^2`), then the entry.  The intermediate numbers of the kernel's
`Nat.shiftRight` are then small except for `n` row extractions per table. -/
namespace E2h
''' + E2_COMMON + r'''
/-- Field `t` of width `w` bits of `T`. -/
def fldW (w T t : Nat) : Nat := Nat.mod (Nat.shiftRight T (Nat.mul w t)) (Nat.pow 2 w)

/-- 64-bit field `t`. -/
def fld (T t : Nat) : Nat := fldW 64 T t

def checkA (n k off hN uN mN : Nat) : Bool :=
  allBelow (fun i => allBelow (fun a =>
    Nat.ble (Nat.add (fld uN i) (Nat.mul (Nat.sub n 1) off))
      (Nat.add (fld hN (ix k i a))
        (sumBelow (fun j =>
          match Nat.beq j i with
          | true => 0
          | false => fld (fldW (Nat.mul 64 (Nat.mul n k)) mN i) (ix k j a)) n))) k) n

/-- One cell of (B).  `t1 = 2 p' i j`, `t2 = 2 p' j i`; `mi`, `mj` = the rows `m i j ·`, `m j i ·`
(k fields each); `bij`, `bji` = the blocks `J i j · ·`, `J j i · ·` (k^2 fields each). -/
def cellOK (k off2 t1 t2 mi mj bij bji a b : Nat) : Bool :=
  le2
    (Nat.add t1 (Nat.add (fld mi a) (fld mj b)))
    (Nat.add t2 (Nat.add (fld mi a) (fld mj b)))
    (Nat.add (Nat.add (fld bij (ix k a b)) (fld bji (ix k b a))) off2)

/-- (B) for the unordered pair `j < i`.  `ri`, `rj` = the parts of the sites `i`, `j` of the `J`
table; `mri`, `mrj` = the parts of the sites `i`, `j` of the message table. -/
def pairOK (n k off pN i j ri rj mri mrj : Nat) : Bool :=
  allBelow (fun a => allBelow (fun b =>
    cellOK k (Nat.mul 2 off)
      (Nat.mul 2 (fld pN (ix n i j))) (Nat.mul 2 (fld pN (ix n j i)))
      (fldW (Nat.mul 64 k) mri j) (fldW (Nat.mul 64 k) mrj i)
      (fldW (Nat.mul 64 (Nat.mul k k)) ri j) (fldW (Nat.mul 64 (Nat.mul k k)) rj i)
      a b) k) k

def checkB (n k off pN mN jN : Nat) : Bool :=
  allBelow (fun i => allBelow (fun j =>
    pairOK n k off pN i j
      (fldW (Nat.mul 64 (Nat.mul n (Nat.mul k k))) jN i)
      (fldW (Nat.mul 64 (Nat.mul n (Nat.mul k k))) jN j)
      (fldW (Nat.mul 64 (Nat.mul n k)) mN i)
      (fldW (Nat.mul 64 (Nat.mul n k)) mN j)) i) n

def checkC (n Lo uN pN : Nat) : Bool :=
  Nat.ble Lo
    (Nat.add (sumBelow (fun i => fld uN i) n)
      (sumBelow (fun i => sumBelow (fun j =>
        match Nat.beq j i with
        | true => 0
        | false => fld pN (ix n i j)) n) n))

/-- The leaf check on packed tables, hierarchical reads. -/
def leafCheck (n k off Lo hN uN pN mN jN : Nat) : Bool :=
  and3 (checkA n k off hN uN mN) (checkB n k off pN mN jN) (checkC n Lo uN pN)

end E2h
'''


def rowmajor_tables(inst):
    n, k = inst['n'], inst['k']
    h, J, m, u, p = (inst[x] for x in ('h', 'J', 'm', 'u', 'p'))
    hT = [h[i][a] for i in range(n) for a in range(k)]
    uT = list(u)
    pT = [p[i][j] for i in range(n) for j in range(n)]
    mT = [m[i][j][a] for i in range(n) for j in range(n) for a in range(k)]
    jT = [J[i][j][a][b] for i in range(n) for j in range(n) for a in range(k) for b in range(k)]
    return hT, uT, pT, mT, jT


def e2_file(inst, claim, tactic, hierarchical, chunk):
    n, k = inst['n'], inst['k']
    hT, uT, pT, mT, jT = rowmajor_tables(inst)
    ns = 'E2h' if hierarchical else 'E2'
    parts = [E2H_CHECKER if hierarchical else E2_CHECKER, '\nnamespace Data\n']
    for name, vals in (('hN', hT), ('uN', uT), ('pN', pT), ('mN', mT), ('jN', jT)):
        parts.append(packed_def(name, [v + OFF for v in vals], chunk))
    Lo = inst['L'] + n * n * OFF
    assert Lo >= 0
    parts.append('def off : Nat := %d\n' % OFF)
    parts.append('def Lo : Nat := %d\n' % Lo)
    parts.append('end Data\n\nopen Data in\n')
    parts.append('theorem %s : %s.leafCheck %d %d off Lo hN uN pN mN jN = %s := by %s\n'
                 % (thm_name(claim), ns, n, k, claim, tactic))
    return ''.join(parts), len(jT)


# ----------------------------------------------------------------------------------------------
# E3: `Array Int` with `Array.getD` (the baseline)
# ----------------------------------------------------------------------------------------------

E3_CHECKER = r'''
/-! Checker E3 (baseline).  Tables are `Array Int` literals in row-major layout, read with
`Array.getD` and index arithmetic: `hA[i k + a]`, `uA[i]`, `pA[i n + j]`, `mA[(i n + j) k + a]`,
`jA[((i n + j) k + a) k + b]` (diagonal blocks present and ignored).  In the kernel an array is a
list, so every read walks the list from the front. -/
namespace E3

/-- `a ≤ b` on `Int` as a `Bool`. -/
def ile : Int → Int → Bool
  | Int.ofNat a, Int.ofNat b => Nat.ble a b
  | Int.ofNat _, Int.negSucc _ => false
  | Int.negSucc _, Int.ofNat _ => true
  | Int.negSucc a, Int.negSucc b => Nat.ble b a

/-- `a - b`. -/
def isub (a b : Int) : Int := Int.add a (Int.neg b)

/-- `t1 ≤ s` and `t2 ≤ s`. -/
def cellLe (t1 t2 s : Int) : Bool :=
  match ile t1 s with
  | true => ile t2 s
  | false => false

/-- `body b` for all `b < c`. -/
def allBelow (body : Nat → Bool) : Nat → Bool
  | 0 => true
  | b+1 =>
      match body b with
      | true => allBelow body b
      | false => false

/-- `Σ_{j < c} f j`. -/
def sumBelow (f : Nat → Int) : Nat → Int
  | 0 => 0
  | j+1 => Int.add (f j) (sumBelow f j)

/-- `i * w + j`. -/
def ix (w i j : Nat) : Nat := Nat.add (Nat.mul i w) j

def rd (A : Array Int) (t : Nat) : Int := A.getD t 0

def and3 (c1 c2 c3 : Bool) : Bool :=
  match c1 with
  | false => false
  | true =>
    match c2 with
    | false => false
    | true => c3

def checkA (n k : Nat) (hA uA mA : Array Int) : Bool :=
  allBelow (fun i => allBelow (fun a =>
    ile (rd uA i)
      (Int.add (rd hA (ix k i a))
        (sumBelow (fun j =>
          match Nat.beq j i with
          | true => 0
          | false => rd mA (ix k (ix n i j) a)) n))) k) n

/-- One cell of (B) for the unordered pair `j < i` (both orientations). -/
def cellOK (n k : Nat) (pA mA jA : Array Int) (i j a b : Nat) : Bool :=
  cellLe (Int.mul 2 (rd pA (ix n i j))) (Int.mul 2 (rd pA (ix n j i)))
    (isub (isub (Int.add (rd jA (ix k (ix k (ix n i j) a) b)) (rd jA (ix k (ix k (ix n j i) b) a)))
      (rd mA (ix k (ix n i j) a))) (rd mA (ix k (ix n j i) b)))

def checkB (n k : Nat) (pA mA jA : Array Int) : Bool :=
  allBelow (fun i => allBelow (fun j => allBelow (fun a => allBelow (fun b =>
    cellOK n k pA mA jA i j a b) k) k) i) n

def checkC (n : Nat) (L : Int) (uA pA : Array Int) : Bool :=
  ile L
    (Int.add (sumBelow (fun i => rd uA i) n)
      (sumBelow (fun i => sumBelow (fun j =>
        match Nat.beq j i with
        | true => 0
        | false => rd pA (ix n i j)) n) n))

/-- The leaf check on arrays. -/
def leafCheck (n k : Nat) (L : Int) (hA uA pA mA jA : Array Int) : Bool :=
  and3 (checkA n k hA uA mA) (checkB n k pA mA jA) (checkC n L uA pA)

end E3
'''


def e3_file(inst, claim, tactic, data_kw):
    n, k = inst['n'], inst['k']
    hT, uT, pT, mT, jT = rowmajor_tables(inst)
    parts = [E3_CHECKER, '\nnamespace Data\n']
    for name, vals in (('hA', hT), ('uA', uT), ('pA', pT), ('mA', mT), ('jA', jT)):
        parts.append('%s %s : Array Int := #[\n%s]\n' % (data_kw, name, int_list(vals)))
    parts.append('def L : Int := %s\n' % int_ctor(inst['L']))
    parts.append('end Data\n\nopen Data in\n')
    parts.append('theorem %s : E3.leafCheck %d %d L hA uA pA mA jA = %s := by %s\n'
                 % (thm_name(claim), n, k, claim, tactic))
    return ''.join(parts), len(jT)


# ----------------------------------------------------------------------------------------------
# E4: flat `List Nat` with offset entries, the same in-order pass as E1
# ----------------------------------------------------------------------------------------------

E4_CHECKER = r'''
/-! Checker E4.  The single in-order pass of E1 on flat lists, but every entry is stored as the
natural number `value + off` (`off = 2^62`), so the arithmetic is `Nat.add` / `Nat.mul` / `Nat.ble`
on literals (which the kernel runs with GMP) instead of `Int` operations (which the kernel has to
unfold constructor by constructor).

Layout: as E1 (`hL`: i, a;  `uL`: i;  `pL`: i < j: `p i j, p j i`;  `mL`: i < j: `m i j ·, m j i ·`;
`jL`: i < j, a, b: `J i j a b, J j i b a`), all entries offset.  `Lo = L + n^2 off`.  With the
offsets the conditions read
  (A) `u' + (n-1) off ≤ h' + Σ_{j≠i} m'`,   (B) `2 p' + m' + m' ≤ J' + J' + 2 off`,
  (C) `Lo ≤ Σ u' + Σ p'`. -/
namespace E4

/-- `x ≤ r` and `y ≤ r`. -/
def le2 (x y r : Nat) : Bool :=
  match Nat.ble x r with
  | true => Nat.ble y r
  | false => false

/-- One cell of (B), both orientations.  `t1 = 2 p' i j`, `t2 = 2 p' j i`, `x = J' i j a b`,
`y = J' j i b a`, `off2 = 2 off`. -/
def cellOK (off2 t1 t2 mia mjb x y : Nat) : Bool :=
  le2 (Nat.add t1 (Nat.add mia mjb)) (Nat.add t2 (Nat.add mia mjb)) (Nat.add (Nat.add x y) off2)

/-- Drop `c` entries. -/
def dropN : Nat → List Nat → List Nat
  | 0, xs => xs
  | _+1, [] => []
  | c+1, _ :: xs => dropN c xs

/-- (B), fixed pair `i < j`, fixed `a`: the cells `b = 0 .. c-1`.  Returns the rest of the `J`
stream, or `none` if a comparison fails or a list is too short. -/
def cellsB (off2 t1 t2 mia : Nat) : Nat → List Nat → List Nat → Option (List Nat)
  | 0, _, js => some js
  | _+1, [], _ => none
  | _+1, _ :: _, [] => none
  | _+1, _ :: _, [_] => none
  | c+1, mjb :: mj, x :: y :: js =>
      match cellOK off2 t1 t2 mia mjb x y with
      | true => cellsB off2 t1 t2 mia c mj js
      | false => none

/-- (B), fixed pair `i < j`: the rows `a = 0 .. c-1`. -/
def rowsB (k off2 t1 t2 : Nat) (mj : List Nat) : Nat → List Nat → List Nat → Option (List Nat)
  | 0, _, js => some js
  | _+1, [], _ => none
  | c+1, mia :: mi, js =>
      match cellsB off2 t1 t2 mia k mj js with
      | some js' => rowsB k off2 t1 t2 mj c mi js'
      | none => none

/-- (B) for the `c` pairs `(i, j)`, `j > i`, of one site `i`. -/
def pairsB (k off2 : Nat) : Nat → List Nat → List Nat → List Nat → Option (List Nat)
  | 0, _, _, js => some js
  | _+1, [], _, _ => none
  | _+1, [_], _, _ => none
  | c+1, pij :: pji :: ps, ms, js =>
      match rowsB k off2 (Nat.mul 2 pij) (Nat.mul 2 pji) (dropN k ms) k ms js with
      | some js' => pairsB k off2 c ps (dropN (Nat.mul 2 k) ms) js'
      | none => none

/-- Entrywise sum of the first `c` entries of two lists. -/
def zipAdd : Nat → List Nat → List Nat → List Nat
  | 0, _, _ => []
  | _+1, [], _ => []
  | _+1, _ :: _, [] => []
  | c+1, x :: xs, y :: ys => Nat.add x y :: zipAdd c xs ys

/-- Entrywise sum of the first `c` entries, followed by `rest`. -/
def zipAddThen (rest : List Nat) : Nat → List Nat → List Nat → List Nat
  | 0, _, _ => rest
  | _+1, [], _ => rest
  | _+1, _ :: _, [] => rest
  | c+1, x :: xs, y :: ys => Nat.add x y :: zipAddThen rest c xs ys

/-- Row of site `i` for (A): `acc` plus the rows `m' i j ·` of the `c` pair records at the front
of `ms`. -/
def addFirst (k : Nat) : Nat → List Nat → List Nat → List Nat
  | 0, acc, _ => acc
  | c+1, acc, ms => addFirst k c (zipAdd k acc ms) (dropN (Nat.mul 2 k) ms)

/-- Pending rows of the sites `j > i`: `others` plus the rows `m' j i ·` of the `c` pair records. -/
def addSecond (k : Nat) : Nat → List Nat → List Nat → List Nat
  | 0, _, _ => []
  | c+1, others, ms =>
      zipAddThen (addSecond k c (dropN k others) (dropN (Nat.mul 2 k) ms)) k others (dropN k ms)

/-- `bound ≤ x` for the first `c` entries `x` of a row (`false` if the row is shorter). -/
def allLe (bound : Nat) : Nat → List Nat → Bool
  | 0, _ => true
  | _+1, [] => false
  | c+1, x :: xs =>
      match Nat.ble bound x with
      | true => allLe bound c xs
      | false => false

/-- Sum of the first `c` entries. -/
def sumN : Nat → List Nat → Nat
  | 0, _ => 0
  | _+1, [] => 0
  | c+1, x :: xs => Nat.add x (sumN c xs)

/-- The whole pass (see E1.sites).  `offA = (n-1) off`. -/
def sites (k off2 offA Lo : Nat) :
    Nat → Nat → List Nat → List Nat → List Nat → List Nat → List Nat → Bool
  | 0, tot, _, _, _, _, _ => Nat.ble Lo tot
  | _+1, _, [], _, _, _, _ => false
  | f+1, tot, u :: us, acc, ps, ms, js =>
      match pairsB k off2 f ps ms js with
      | none => false
      | some js' =>
        match allLe (Nat.add u offA) k (addFirst k f acc ms) with
        | false => false
        | true =>
          sites k off2 offA Lo f (Nat.add tot (Nat.add u (sumN (Nat.mul 2 f) ps))) us
            (addSecond k f (dropN k acc) ms) (dropN (Nat.mul 2 f) ps)
            (dropN (Nat.mul (Nat.mul 2 k) f) ms) js'

/-- The leaf check on the stream layout with offset entries. -/
def leafCheck (n k off Lo : Nat) (hL uL pL mL jL : List Nat) : Bool :=
  sites k (Nat.mul 2 off) (Nat.mul (Nat.sub n 1) off) Lo n 0 uL hL pL mL jL

end E4
'''


def e4_file(inst, claim, tactic, data_kw, list_chunk):
    n, k = inst['n'], inst['k']
    hL, uL, pL, mL, jL = e1_tables(inst)
    parts = [E4_CHECKER, '\nnamespace Data\n']
    for name, vals in (('hL', hL), ('uL', uL), ('pL', pL), ('mL', mL), ('jL', jL)):
        parts.append(list_def(data_kw, name, 'Nat', [str(v + OFF) for v in vals], list_chunk))
    Lo = inst['L'] + n * n * OFF
    assert Lo >= 0
    parts.append('def off : Nat := %d\n' % OFF)
    parts.append('def Lo : Nat := %d\n' % Lo)
    parts.append('end Data\n\nopen Data in\n')
    parts.append('theorem %s : E4.leafCheck %d %d off Lo hL uL pL mL jL = %s := by %s\n'
                 % (thm_name(claim), n, k, claim, tactic))
    return ''.join(parts), len(jL)


