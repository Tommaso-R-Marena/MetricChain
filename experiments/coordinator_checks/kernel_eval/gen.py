E1_CHECKER = r'''
/-! Checker E1.  Every table is a flat `List Int`, consumed front to back; nothing is indexed.

Layout (the "stream order", fixed by the generator):
* `hL` : for i, for a:  `h i a`                                         (n k entries)
* `uL` : for i:  `u i`                                                  (n)
* `pL` : for i < j (lexicographic):  `p i j, p j i`                      (n (n-1))
* `mL` : for i < j:  `m i j 0 .. m i j (k-1), m j i 0 .. m j i (k-1)`    (n (n-1) k)
* `jL` : for i < j, for a, for b:  `J i j a b, J j i b a`                (n (n-1) k^2)
-/
namespace E1

/-- `a ≤ b` on `Int` as a `Bool` (four constructor cases, `Nat.ble` inside). -/
def ile : Int → Int → Bool
  | Int.ofNat a, Int.ofNat b => Nat.ble a b
  | Int.ofNat _, Int.negSucc _ => false
  | Int.negSucc _, Int.ofNat _ => true
  | Int.negSucc a, Int.negSucc b => Nat.ble b a

/-- `a - b`, spelled with `Int.add` and `Int.neg` (no type-class instances to unfold). -/
def isub (a b : Int) : Int := Int.add a (Int.neg b)

/-- `t1 ≤ s` and `t2 ≤ s`. -/
def cellLe (t1 t2 s : Int) : Bool :=
  match ile t1 s with
  | true => ile t2 s
  | false => false

/-- One cell of (B): `2 p i j ≤ J i j a b + J j i b a - m i j a - m j i b` and the same with
`p j i` (the inequality for the ordered pair `(j, i)` and the states `(b, a)` has the same
right-hand side).  `t1 = 2 p i j`, `t2 = 2 p j i`, `x = J i j a b`, `y = J j i b a`. -/
def cellOK (t1 t2 mia mjb x y : Int) : Bool :=
  cellLe t1 t2 (isub (isub (Int.add x y) mia) mjb)

/-- Drop `c` entries. -/
def dropN : Nat → List Int → List Int
  | 0, xs => xs
  | _+1, [] => []
  | c+1, _ :: xs => dropN c xs

/-- (B), fixed pair `i < j`, fixed `a`: the cells `b = 0 .. c-1`.  `mj` = `m j i b, …`;
`js` = the `J` stream.  Returns the rest of the `J` stream, or `none` if a comparison fails or a
list is too short. -/
def cellsB (t1 t2 mia : Int) : Nat → List Int → List Int → Option (List Int)
  | 0, _, js => some js
  | _+1, [], _ => none
  | _+1, _ :: _, [] => none
  | _+1, _ :: _, [_] => none
  | c+1, mjb :: mj, x :: y :: js =>
      match cellOK t1 t2 mia mjb x y with
      | true => cellsB t1 t2 mia c mj js
      | false => none

/-- (B), fixed pair `i < j`: the rows `a = 0 .. c-1`.  `mi` = `m i j a, …`; `mj` = the `k` values
`m j i ·` (read again for every `a`). -/
def rowsB (k : Nat) (t1 t2 : Int) (mj : List Int) : Nat → List Int → List Int → Option (List Int)
  | 0, _, js => some js
  | _+1, [], _ => none
  | c+1, mia :: mi, js =>
      match cellsB t1 t2 mia k mj js with
      | some js' => rowsB k t1 t2 mj c mi js'
      | none => none

/-- (B) for the `c` pairs `(i, j)`, `j > i`, of one site `i`. -/
def pairsB (k : Nat) : Nat → List Int → List Int → List Int → Option (List Int)
  | 0, _, _, js => some js
  | _+1, [], _, _ => none
  | _+1, [_], _, _ => none
  | c+1, pij :: pji :: ps, ms, js =>
      match rowsB k (Int.mul 2 pij) (Int.mul 2 pji) (dropN k ms) k ms js with
      | some js' => pairsB k c ps (dropN (Nat.mul 2 k) ms) js'
      | none => none

/-- Entrywise sum of the first `c` entries of two lists. -/
def zipAdd : Nat → List Int → List Int → List Int
  | 0, _, _ => []
  | _+1, [], _ => []
  | _+1, _ :: _, [] => []
  | c+1, x :: xs, y :: ys => Int.add x y :: zipAdd c xs ys

/-- Entrywise sum of the first `c` entries, followed by `rest`. -/
def zipAddThen (rest : List Int) : Nat → List Int → List Int → List Int
  | 0, _, _ => rest
  | _+1, [], _ => rest
  | _+1, _ :: _, [] => rest
  | c+1, x :: xs, y :: ys => Int.add x y :: zipAddThen rest c xs ys

/-- Row of site `i` for (A): `acc` (its first `k` entries) plus the rows `m i j ·` of the `c` pair
records `(i, j)`, `j > i`, at the front of `ms`. -/
def addFirst (k : Nat) : Nat → List Int → List Int → List Int
  | 0, acc, _ => acc
  | c+1, acc, ms => addFirst k c (zipAdd k acc ms) (dropN (Nat.mul 2 k) ms)

/-- Pending rows of the sites `j > i`: `others` plus the rows `m j i ·` of the `c` pair records. -/
def addSecond (k : Nat) : Nat → List Int → List Int → List Int
  | 0, _, _ => []
  | c+1, others, ms =>
      zipAddThen (addSecond k c (dropN k others) (dropN (Nat.mul 2 k) ms)) k others (dropN k ms)

/-- `u ≤ x` for the first `c` entries `x` of a row (`false` if the row is shorter). -/
def allLe (u : Int) : Nat → List Int → Bool
  | 0, _ => true
  | _+1, [] => false
  | c+1, x :: xs =>
      match ile u x with
      | true => allLe u c xs
      | false => false

/-- Sum of the first `c` entries. -/
def sumN : Nat → List Int → Int
  | 0, _ => 0
  | _+1, [] => 0
  | c+1, x :: xs => Int.add x (sumN c xs)

/-- The whole pass.  First argument: number of sites still to do (`f` = sites after the current
one).  `tot` = `Σ u + Σ p` so far; `acc` = for the current and all later sites `s` the row
`h s · + Σ_{j < current} m s j ·` (flat, `k` entries per site). -/
def sites (k : Nat) (L : Int) :
    Nat → Int → List Int → List Int → List Int → List Int → List Int → Bool
  | 0, tot, _, _, _, _, _ => ile L tot
  | _+1, _, [], _, _, _, _ => false
  | f+1, tot, u :: us, acc, ps, ms, js =>
      match pairsB k f ps ms js with
      | none => false
      | some js' =>
        match allLe u k (addFirst k f acc ms) with
        | false => false
        | true =>
          sites k L f (Int.add tot (Int.add u (sumN (Nat.mul 2 f) ps))) us
            (addSecond k f (dropN k acc) ms) (dropN (Nat.mul 2 f) ps)
            (dropN (Nat.mul (Nat.mul 2 k) f) ms) js'

/-- The leaf check on the stream layout. -/
def leafCheck (n k : Nat) (L : Int) (hL uL pL mL jL : List Int) : Bool :=
  sites k L n 0 uL hL pL mL jL

end E1
'''


def e1_tables(inst):
    n, k = inst['n'], inst['k']
    h, J, m, u, p = (inst[x] for x in ('h', 'J', 'm', 'u', 'p'))
    hL = [h[i][a] for i in range(n) for a in range(k)]
    uL = list(u)
    pL, mL, jL = [], [], []
    for i in range(n):
        for j in range(i + 1, n):
            pL += [p[i][j], p[j][i]]
            mL += m[i][j] + m[j][i]
            for a in range(k):
                for b in range(k):
                    jL += [J[i][j][a][b], J[j][i][b][a]]
    return hL, uL, pL, mL, jL


def e1_file(inst, claim, tactic, data_kw, list_chunk):
    n, k = inst['n'], inst['k']
    hL, uL, pL, mL, jL = e1_tables(inst)
    parts = [E1_CHECKER, '\nnamespace Data\n']
    for name, vals in (('hL', hL), ('uL', uL), ('pL', pL), ('mL', mL), ('jL', jL)):
        parts.append(list_def(data_kw, name, 'Int', [int_ctor(v) for v in vals], list_chunk))
    parts.append('def L : Int := %s\n' % int_ctor(inst['L']))
    parts.append('end Data\n\nopen Data in\n')
    parts.append('theorem %s : E1.leafCheck %d %d L hL uL pL mL jL = %s := by %s\n'
                 % (thm_name(claim), n, k, claim, tactic))
    return ''.join(parts), len(jL)


