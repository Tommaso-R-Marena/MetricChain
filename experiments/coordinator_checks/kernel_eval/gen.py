#!/usr/bin/env python3
"""Generator for the kernel-evaluation feasibility experiment (see README.md).

For a size (n, k) it draws a random pairwise instance with integer tables of about 40 bits
(signed), takes a certificate for the leaf check

  (A) for all i, a:            u i <= h i a + sum_{j != i} m i j a
  (B) for all i != j, a, b:    2 * p i j <= J i j a b + J j i b a - m i j a - m j i b
  (C) L <= sum_i u i + sum_i sum_{j != i} p i j

that is true and tight (u i = the minimum in (A), p i j = floor(minimum in (B) / 2), L = the sum
in (C)), and writes one self-contained Lean file per ENCODING of tables and checker.  Every Lean
file imports nothing and ends in a theorem `leafCheck ... = true` (or `= false` for the negative
controls) proved by `decide +kernel`.

Encodings (the Lean source of each checker is a string constant below):
  E1   flat `List Int`, one in-order pass, no indexing
  E4   the same pass on flat `List Nat` with offset entries
  E2   one big `Nat` per table (64-bit fields), flat reads by shift and mod
  E2h  the same packed tables, hierarchical reads (site part, pair block, entry)
  E3   `Array Int` with `Array.getD` (baseline)

Standard library only; the random data depend only on (n, k, --seed, --messages), so every file
can be regenerated byte for byte (run.sh records the SHA-256 of each file it runs).

    python3 gen.py --out generated --n 16 --k 2 --enc E1 E2 E3 --controls
    python3 gen.py --list
"""
import argparse
import os
import random
import sys

# (8, 2) is an extra tiny size: the only one the array baseline E3 gets through
SIZES = [(8, 2), (16, 2), (16, 4), (32, 4), (32, 8), (48, 8)]
BITS = 40                  # table entries are drawn uniformly from [-2^39, 2^39)
OFF = 1 << 62              # offset that makes every packed 64-bit field nonnegative (E2, E2h, E4)
FIELD = 64                 # width of a packed field in bits
ENCODINGS = ['E1', 'E2', 'E2h', 'E3', 'E4']
MUTATIONS = ['negL', 'negU', 'negP', 'negJ', 'negJ0']


# ----------------------------------------------------------------------------------------------
# instance, certificate, reference check
# ----------------------------------------------------------------------------------------------

def make_instance(n, k, seed, messages='zero'):
    """Random tables and the tight certificate.  Diagonal blocks (i = j) are zero and never used."""
    rng = random.Random('kernel_eval/%d/%d/%d' % (n, k, seed))
    lo, hi = -(1 << (BITS - 1)), (1 << (BITS - 1)) - 1
    h = [[rng.randint(lo, hi) for _ in range(k)] for _ in range(n)]
    J = [[[[rng.randint(lo, hi) if i != j else 0 for _ in range(k)] for _ in range(k)]
          for j in range(n)] for i in range(n)]
    if messages == 'zero':
        m = [[[0] * k for _ in range(n)] for _ in range(n)]
    elif messages == 'random':
        mrng = random.Random('kernel_eval/messages/%d/%d/%d' % (n, k, seed))
        m = [[[mrng.randint(lo, hi) if i != j else 0 for _ in range(k)] for j in range(n)]
             for i in range(n)]
    else:
        raise ValueError(messages)
    u = [min(h[i][a] + sum(m[i][j][a] for j in range(n) if j != i) for a in range(k))
         for i in range(n)]
    p = [[0] * n for _ in range(n)]
    for i in range(n):
        for j in range(n):
            if i != j:
                best = min(J[i][j][a][b] + J[j][i][b][a] - m[i][j][a] - m[j][i][b]
                           for a in range(k) for b in range(k))
                p[i][j] = best // 2            # Python's // is the floor
    L = sum(u) + sum(p[i][j] for i in range(n) for j in range(n) if i != j)
    return {'n': n, 'k': k, 'h': h, 'J': J, 'm': m, 'u': u, 'p': p, 'L': L,
            'seed': seed, 'messages': messages}


def reference_check(inst):
    """The leaf check, straight from its definition.  Returns the truth values of (A), (B), (C)."""
    n, k = inst['n'], inst['k']
    h, J, m, u, p, L = (inst[x] for x in ('h', 'J', 'm', 'u', 'p', 'L'))
    okA = all(u[i] <= h[i][a] + sum(m[i][j][a] for j in range(n) if j != i)
              for i in range(n) for a in range(k))
    okB = all(2 * p[i][j] <= J[i][j][a][b] + J[j][i][b][a] - m[i][j][a] - m[j][i][b]
              for i in range(n) for j in range(n) if i != j
              for a in range(k) for b in range(k))
    okC = L <= sum(u) + sum(p[i][j] for i in range(n) for j in range(n) if i != j)
    return okA, okB, okC


def mutate(inst, kind):
    """Negative controls.  Each one breaks exactly one of (A), (B), (C)."""
    n, k = inst['n'], inst['k']
    out = dict(inst)
    if kind == 'negL':                         # (C) fails: the bound is tight
        out['L'] = inst['L'] + 1
        expect = (True, True, False)
    elif kind == 'negU':                       # (A) fails at one site: u is the exact minimum
        u = list(inst['u'])
        u[n // 2] += 1
        out['u'] = u
        expect = (False, True, True)
    elif kind == 'negP':                       # (B) fails for one ordered pair (i > j)
        p = [row[:] for row in inst['p']]
        p[n - 1][0] += 1
        out['p'] = p
        expect = (True, False, True)
    elif kind in ('negJ', 'negJ0'):            # (B) fails in exactly one cell:
        J = [[[row[:] for row in blk] for blk in line] for line in inst['J']]
        if kind == 'negJ':                     #   the last cell of the last pair, or
            i, j, a, b = n - 2, n - 1, k - 1, k - 1
        else:                                  #   the first cell of the first pair
            i, j, a, b = 0, 1, 0, 0
        m = inst['m']
        # make  J i j a b + J j i b a - m i j a - m j i b  =  2 p i j - 1
        J[j][i][b][a] = 2 * inst['p'][i][j] - 1 - J[i][j][a][b] + m[i][j][a] + m[j][i][b]
        out['J'] = J
        expect = (True, False, True)
    else:
        raise ValueError(kind)
    got = reference_check(out)
    assert got == expect, (kind, got, expect)
    return out


