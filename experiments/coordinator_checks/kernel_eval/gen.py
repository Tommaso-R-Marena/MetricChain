PLAIN_INT_NUMERALS = False     # set by --plain-int-numerals (side experiment only)


def int_ctor(v):
    """An `Int` in constructor form: `Int.ofNat a` is a, `Int.negSucc a` is -(a+1).

    Plain numerals (`-5`) are not used: a long `List Int` literal of plain numerals does not even
    elaborate (a 960-entry list runs into the elaborator's 200000-heartbeat limit, see
    --plain-int-numerals), and the kernel would have to unfold `Neg.neg`/`OfNat.ofNat` for every
    entry."""
    if PLAIN_INT_NUMERALS:
        return str(v)
    return 'Int.ofNat %d' % v if v >= 0 else 'Int.negSucc %d' % (-v - 1)


def int_list(values, per_line=6, indent='  '):
    lines = []
    for s in range(0, len(values), per_line):
        lines.append(indent + ', '.join(int_ctor(v) for v in values[s:s + per_line]))
    return ',\n'.join(lines)


def list_def(kw, name, elem_type, items, chunk, per_line=6):
    """`<kw> name : List elem_type := ...` for the given item strings.

    chunk = 0 or a short list: ONE list literal `[a, b, ...]`.  Otherwise the list is written as a
    chain of constants, `name := a :: b :: ... :: name_c1`, `name_c1 := ... :: name_c2`, ..., the
    last one a literal; each constant holds `chunk` entries.  The value is the same flat list (the
    kernel passes from one chunk to the next with one unfolding), but every command stays small:
    one literal with 63488 numerals hits the elaborator's heartbeat limit, and its elaboration
    time grows faster than linearly (see README.md)."""
    def body(part, tail):
        lines = []
        for s in range(0, len(part), per_line):
            lines.append('  ' + (', ' if tail is None else ' :: ').join(part[s:s + per_line]))
        if tail is None:
            return '[\n' + ',\n'.join(lines) + ']'
        return ' ::\n'.join(lines) + ' ::\n  ' + tail
    if chunk <= 0 or len(items) <= chunk:
        return '%s %s : List %s := %s\n' % (kw, name, elem_type, body(items, None))
    starts = list(range(0, len(items), chunk))
    names = [name] + ['%s_c%d' % (name, t) for t in range(1, len(starts))]
    out = []
    for t in reversed(range(len(starts))):
        part = items[starts[t]:starts[t] + chunk]
        tail = names[t + 1] if t + 1 < len(starts) else None
        if tail is None:
            out.append('%s %s : List %s := %s\n' % (kw, names[t], elem_type, body(part, None)))
        else:
            out.append('%s %s : List %s :=\n%s\n' % (kw, names[t], elem_type, body(part, tail)))
    return ''.join(out)


def packed_value(fields):
    """Fields (each in [0, 2^64)) packed little-endian: field t occupies bits [64 t, 64 t + 64)."""
    val = 0
    for t, f in enumerate(fields):
        assert 0 <= f < (1 << FIELD), f
        val |= f << (FIELD * t)
    return val


def hex_literal(val, ndigits):
    return '0x' + format(val, '0%dx' % max(ndigits, 1))


def packed_def(name, fields, chunk):
    """`def name : Nat := ...` holding the packed fields.

    chunk = 0: ONE hexadecimal literal.  chunk > 0: literals of at most `chunk` fields each,
    combined by a balanced tree of `Nat.add lo (Nat.shiftLeft hi bits)` (the kernel evaluates this
    expression once with GMP and caches the resulting literal; `Nat.add` and not `Nat.lor`, whose
    definition in core depends on `propext`)."""
    nf = len(fields)
    if chunk <= 0 or nf <= chunk:
        return 'def %s : Nat :=\n  %s\n' % (name, hex_literal(packed_value(fields), 16 * nf))

    pieces = []

    def build(lo, hi):
        if hi - lo <= chunk:
            cname = '%s_c%d' % (name, len(pieces))
            pieces.append('def %s : Nat :=\n  %s\n' % (
                cname, hex_literal(packed_value(fields[lo:hi]), 16 * (hi - lo))))
            return cname
        nchunks = (hi - lo + chunk - 1) // chunk
        mid = lo + chunk * (nchunks // 2)
        left = build(lo, mid)
        right = build(mid, hi)
        return '(Nat.add %s (Nat.shiftLeft %s %d))' % (left, right, FIELD * (mid - lo))

    expr = build(0, nf)
    return ''.join(pieces) + 'def %s : Nat :=\n  %s\n' % (name, expr)


