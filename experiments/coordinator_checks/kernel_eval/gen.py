def thm_name(claim):
    return 'check_ok' if claim == 'true' else 'check_is_false'


def header(enc, inst, variant, claim, tactic, entries):
    n, k = inst['n'], inst['k']
    return ('/-\n'
            'GENERATED by experiments/coordinator_checks/kernel_eval/gen.py -- do not edit.\n'
            'encoding %s, n = %d sites, k = %d states, %d entries in the J table of this encoding\n'
            '(n^2 k^2 = %d), entries %d-bit signed, messages: %s, seed %d, variant: %s.\n'
            'Claim: leafCheck ... = %s, tactic: %s.\n'
            'Imports nothing (core Lean only).\n'
            '-/\n'
            % (enc, n, k, entries, n * n * k * k, BITS, inst['messages'], inst['seed'], variant,
               claim, tactic))


def render(enc, inst, variant, claim, tactic, chunk, plain_def=False, list_chunk=128):
    # List and array tables are `noncomputable def`s: only the kernel has to see them, and Lean's
    # code generator fails on a long list literal ("maximum recursion depth has been reached" for
    # 3840 entries; reproduce with --plain-def).
    data_kw = 'def' if plain_def else 'noncomputable def'
    if enc == 'E1':
        body, entries = e1_file(inst, claim, tactic, data_kw, list_chunk)
    elif enc == 'E2':
        body, entries = e2_file(inst, claim, tactic, False, chunk)
    elif enc == 'E2h':
        body, entries = e2_file(inst, claim, tactic, True, chunk)
    elif enc == 'E3':
        body, entries = e3_file(inst, claim, tactic, data_kw)
    elif enc == 'E4':
        body, entries = e4_file(inst, claim, tactic, data_kw, list_chunk)
    else:
        raise ValueError(enc)
    text = header(enc, inst, variant, claim, tactic, entries) + body
    if claim == 'true':
        text += '\n#print axioms check_ok\n'
    else:
        text += '\n#print axioms check_is_false\n'
    return text


def file_name(enc, n, k, variant, suffix=''):
    name = '%s_n%d_k%d' % (enc, n, k)
    if variant != 'pos':
        name += '_' + variant
    return name + suffix + '.lean'


def write(out_dir, name, text):
    path = os.path.join(out_dir, name)
    with open(path, 'w') as fh:
        fh.write(text)
    return path


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--out', default='generated')
    ap.add_argument('--n', type=int)
    ap.add_argument('--k', type=int)
    ap.add_argument('--enc', nargs='+', default=ENCODINGS, choices=ENCODINGS)
    ap.add_argument('--seed', type=int, default=20261126)
    ap.add_argument('--messages', default='zero', choices=['zero', 'random'])
    ap.add_argument('--controls', action='store_true',
                    help='also write the negative controls and the `decide` / `rfl` variants')
    ap.add_argument('--tactic-variants', action='store_true',
                    help='also write the `decide` / `rfl` variants (without the negative controls)')
    ap.add_argument('--chunk-fields', type=int, default=256,
                    help='E2/E2h: write each packed table as literals of at most this many fields '
                         'combined with Nat.add/Nat.shiftLeft (0 = ONE literal per table; Lean '
                         'decodes a long numeral in quadratic time, see README.md)')
    ap.add_argument('--list-chunk', type=int, default=128,
                    help='E1/E4: write each list as a chain of constants of this many entries '
                         '(0 = ONE list literal per table)')
    ap.add_argument('--plain-def', action='store_true',
                    help='E1/E3/E4: plain `def` instead of `noncomputable def` for the tables')
    ap.add_argument('--plain-int-numerals', action='store_true',
                    help='E1/E3: write `Int` entries as plain numerals (`-5`) instead of '
                         'constructor form; a long list of them does not elaborate')
    ap.add_argument('--data-only', action='store_true',
                    help='positive file without the theorem (checker and tables only): what '
                         'parsing and elaborating the tables costs without the kernel evaluation')
    ap.add_argument('--suffix', default='', help='appended to the file names')
    ap.add_argument('--list', action='store_true', help='print the sizes and exit')
    args = ap.parse_args()

    if args.list:
        for n, k in SIZES:
            print('n=%d k=%d  n^2k^2=%d  unordered cells=%d' %
                  (n, k, n * n * k * k, n * (n - 1) // 2 * k * k))
        return 0
    if args.n is None or args.k is None:
        ap.error('--n and --k are required')

    global PLAIN_INT_NUMERALS
    PLAIN_INT_NUMERALS = args.plain_int_numerals
    os.makedirs(args.out, exist_ok=True)
    inst = make_instance(args.n, args.k, args.seed, args.messages)
    assert reference_check(inst) == (True, True, True)
    written = []
    for enc in args.enc:
        text = render(enc, inst, 'pos', 'true', 'decide +kernel', args.chunk_fields,
                      args.plain_def, args.list_chunk)
        if args.data_only:
            cut = text.index('\nopen Data in\ntheorem ')
            text = text[:cut] + '\n-- data only: the theorem is omitted on purpose\n'
        written.append(write(args.out, file_name(enc, args.n, args.k, 'pos', args.suffix), text))
        if args.controls:
            for kind in MUTATIONS:
                bad = mutate(inst, kind)
                text = render(enc, bad, kind, 'false', 'decide +kernel', args.chunk_fields,
                              False, args.list_chunk)
                written.append(write(args.out, file_name(enc, args.n, args.k, kind), text))
            bad = mutate(inst, 'negL')
            text = render(enc, bad, 'negL, WRONG CLAIM (must be rejected)', 'true',
                          'decide +kernel', args.chunk_fields, False, args.list_chunk)
            written.append(write(args.out, file_name(enc, args.n, args.k, 'negL_claimtrue'), text))
        if args.controls or args.tactic_variants:
            for tac, tag in (('decide', 'tac_decide'), ('rfl', 'tac_rfl')):
                text = render(enc, inst, 'pos, tactic variant', 'true', tac, args.chunk_fields,
                              False, args.list_chunk)
                written.append(write(args.out, file_name(enc, args.n, args.k, tag), text))
    for path in written:
        print('%s  %d bytes' % (path, os.path.getsize(path)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
