#!/usr/bin/env python3
"""R2 — a RIGOROUS lower bound for liminf_N N^P_cov(eps1 N) that uses more of K^br than the triangle T0.

Proved points of K^br (4D, (p; g)):
  exact:  rod (0,0,0;0), row of stems (1/2,2,3/2;0), crystal (1,5,6;0)  [Prop 11.72(d)],
          all-gauche helix (0,0,1;1)  [bridge with h=(0,0,N-3), g=N-3 for every N];
  approximate: explicit finite bridges (generated by the authors' builder, VERIFIED by my code):
          a point of K^br within delta_i = 168/(N_i+3) of (h,g)/N_i  (norm ||dp||_c + |dg|; Theorem 11.69).
K^br is convex, so for weights lambda the point sum lambda_i q_i^* is in K^br and within
d(lambda) = sum lambda_i delta_i of the computable point (p,g) = sum lambda_i q_i.
If computable points satisfy   L||p_i-p_j||_c > e(g_i+g_j) + 2 eps1 + max(L,e)(d_i+d_j)   pairwise,
the true points satisfy the hypothesis of Theorem 11.71(b), hence liminf N^P_cov(eps1 N) >= k
(walks and bridges).  Everything is re-verified in exact rational arithmetic.
"""
import json, os, sys, itertools, random
from fractions import Fraction as Fr
import numpy as np
from scipy.optimize import linprog
from scipy.spatial import ConvexHull, Delaunay
HERE=os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0,HERE)
from r2_lattice import norm_c
V=[((Fr(0),Fr(0),Fr(0),Fr(0)),Fr(0)),((Fr(1,2),Fr(2),Fr(3,2),Fr(0)),Fr(0)),((Fr(1),Fr(5),Fr(6),Fr(0)),Fr(0)),((Fr(0),Fr(0),Fr(1),Fr(1)),Fr(0))]
J=json.load(open(f"{HERE}/out/witness_points_W64.json"))+[["big",166199,[1717,376013,687789,131710]]]
for n,N,q in J: V.append((tuple(Fr(c,N) for c in q),Fr(168,N+3)))
Q=np.array([[float(c) for c in q] for q,_ in V]); DL=np.array([float(d) for _,d in V])
U=np.array([[5,0,0],[3,3,0],[1,1,1]],float)
def envelope(p):
    """min g + (credit for the uncertainty) over convex combinations with projection p"""
    k=len(V)
    r=linprog(Q[:,3]+DL, A_eq=np.vstack([Q[:,:3].T,np.ones(k)]), b_eq=np.append(p,1.0), bounds=(0,None), method="highs")
    return (r.x if r.status==0 else None)
def run(L,eps1,step,g0=60,norders=24,seed=0,tag=''):
    hull=Delaunay(Q[:,:3])
    lo=Q[:,:3].min(0); hi=Q[:,:3].max(0)
    # grid in u-coordinates
    Uq=Q[:,:3]@U.T; ulo=Uq.min(0); uhi=Uq.max(0)
    grid=[]
    for a in np.arange(ulo[0],uhi[0]+1e-9,step):
        for b in np.arange(ulo[1],uhi[1]+1e-9,step):
            for c in np.arange(ulo[2],uhi[2]+1e-9,step):
                p=np.linalg.solve(U,np.array([a,b,c]))
                if hull.find_simplex(p)>=0: grid.append(p)
    pts=[]; lams=[]
    for p in grid:
        lam=envelope(p)
        if lam is None: continue
        # rationalise
        lf=[Fr(float(x)).limit_denominator(10**6) if x>1e-9 else Fr(0) for x in lam]
        s=sum(lf)
        if s==0: continue
        lf=[x/s for x in lf]
        pe=tuple(sum(lf[i]*V[i][0][k] for i in range(len(V))) for k in range(4)); de=sum(lf[i]*V[i][1] for i in range(len(V)))
        pts.append((pe,de)); lams.append(lf)
    # the vertices themselves
    for i,(q,d) in enumerate(V):
        pts.append((q,d)); lams.append([Fr(1) if j==i else Fr(0) for j in range(len(V))])
    # a fine grid in T0 (exact points, g = 0, no uncertainty)
    G0=g0
    V1=V[1][0]; V2=V[2][0]
    for a in range(G0+1):
        for b in range(G0+1-a):
            pts.append((tuple((a*V1[k]+b*V2[k])/G0 for k in range(4)),Fr(0)))
            lams.append([Fr(G0-a-b,G0),Fr(a,G0),Fr(b,G0)]+[Fr(0)]*(len(V)-3))
    n=len(pts)
    P=np.array([[float(c) for c in q] for q,_ in pts]); D=np.array([float(d) for _,d in pts])
    Pu=P[:,:3]@U.T
    mx=float(max(L,1))
    rad=P[:,3]+float(eps1)+mx*D            # e=1
    rng=random.Random(seed)
    orders=[np.argsort(rad,kind="stable"), np.argsort(rad+0.02*Pu.sum(1)), np.argsort(rad-0.02*Pu.sum(1)), np.argsort(Pu.sum(1)), np.argsort(-Pu.sum(1))]
    for t in range(norders):
        orders.append(np.argsort(rad+rng.random()*0.3*np.array([rng.random() for _ in range(n)])))
    best=[]
    for o in orders:
        ch=[]; C=np.empty((0,3)); R=np.empty(0)
        for i in o:
            if len(ch)==0 or np.all(float(L)*np.abs(C-Pu[i]).sum(1) > (R+rad[i])*(1+1e-9)+1e-9):
                ch.append(i); C=np.vstack([C,Pu[i]]); R=np.append(R,rad[i])
        if len(ch)>len(best): best=ch
    # exact verification
    ok=True
    for a,b in itertools.combinations(best,2):
        (qa,da),(qb,db)=pts[a],pts[b]
        lhs=L*norm_c(tuple(qa[k]-qb[k] for k in range(3)))
        rhs=(qa[3]+qb[3])+2*eps1+max(L,Fr(1))*(da+db)
        ok&=(lhs>rhs)
    nT0=sum(1 for i in best if pts[i][0][3]==0)
    if tag:
        with open(f"{HERE}/out/rigorous_packing_{tag}.txt","w") as f:
            f.write("# one packing point per line: the weights lambda_1..lambda_%d (rationals, sum 1) on the proved points listed in out/rigorous_packing_vertices.txt\n" % len(V))
            for i in best: f.write(" ".join(str(c) for c in lams[i])+"\n")
        with open(f"{HERE}/out/rigorous_packing_vertices.txt","w") as f:
            f.write("# proved points of K^br: p3 p8 p11 g delta  (delta = 0: exact; else 168/(N+3))\n")
            for q,d in V: f.write(" ".join(str(c) for c in q)+" "+str(d)+"\n")
    return len(best),ok,n,nT0
if __name__=="__main__":
    print(f"{len(V)} proved points of K^br (4 exact, {len(V)-4} verified finite bridges); largest delta = {float(max(d for _,d in V)):.5f}")
    for name,L,e1,step,g0,tag in [("(1,1/2)",Fr(1),Fr(1,2),0.14,90,"L1_e12"),("(1,1/4)",Fr(1),Fr(1,4),0.11,180,"L1_e14"),("(1/5,1/2)",Fr(1,5),Fr(1,2),0.35,28,"L15_e12"),("(1/5,1/4)",Fr(1,5),Fr(1,4),0.25,56,"L15_e14")]:
        k,ok,n,nT0=run(L,e1,step,g0=g0,tag=tag)
        print(f"  {name}: packing of {k} points (of {n} candidates; {nT0} with g=0) satisfying the hypothesis of Theorem 11.71(b) with the uncertainty margin; exact verification: {ok}",flush=True)
