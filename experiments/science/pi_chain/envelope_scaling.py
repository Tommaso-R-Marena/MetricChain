"""Scaling with chain length of identified sets under model + envelope class + averaged data.

For n torsions (N = n + 3 beads), model = athermal chain = truth, envelope constant b per torsion,
exact data = model averages of (i) nothing, (ii) Rg^2, (iii) the three-shell profile.
Reports widths of the identified interval of each target.  Uses envelope_identified.py.
Also: b_min(data) = smallest b for which data generated by a DIFFERENT truth are consistent
with the model's envelope class (bisection on LP feasibility): a certified lower bound on the
model error implied by the data.
"""
import sys, json, time
import numpy as np
from envelope_identified import setup, interval

def bmin(S, model, Phi, m, lo=0.0, hi=4.0, tol=1e-3):
    psi = np.zeros(S["M"])
    if interval(S, model, psi, b=hi, Phi=Phi, m=m) is None:
        return None
    while hi - lo > tol:
        mid = 0.5 * (lo + hi)
        if interval(S, model, psi, b=mid, Phi=Phi, m=m) is None: lo = mid
        else: hi = mid
    return hi

if __name__ == "__main__":
    ns = [int(v) for v in sys.argv[1:]] or [3, 4, 5, 6]
    out = []
    for n in ns:
        t0 = time.time()
        S = setup(n); sa = S["sa"]
        model = sa.astype(float); model /= model.sum()
        thr = np.quantile(S["rg2"][sa], 0.10)
        targets = {"gauche fraction": S["gau"] / n, "P(compact decile)": (sa & (S["rg2"] <= thr)).astype(float),
                   "end-to-end R2 / max": S["ree2"] / S["ree2"].max()}
        datas = {"no data": None, "Rg2": S["rg2"][:, None], "three-shell profile": S["prof"]}
        for b in (0.5, 1.0):
            for dname, Phi in datas.items():
                m = None if Phi is None else model @ Phi
                for sname, psi in targets.items():
                    iv = interval(S, model, psi, b=b, Phi=Phi, m=m)
                    rng = float(psi[sa].max() - psi[sa].min())
                    out.append(dict(n=n, b=b, data=dname, target=sname, lo=iv[0], hi=iv[1],
                                    width=iv[1] - iv[0], rel_width=(iv[1] - iv[0]) / rng,
                                    truth=float(model @ psi)))
                    print(f"n={n} b={b} {dname:20s} {sname:20s} [{iv[0]:.4f}, {iv[1]:.4f}] width {iv[1]-iv[0]:.4f} "
                          f"({(iv[1]-iv[0])/rng:.3f} of range)", flush=True)
        # falsification: truth = attractive chain exp(+eps*c3); data = its three-shell profile / Rg2
        for eps in (0.25, 0.5, 1.0):
            w = sa * np.exp(eps * S["prof"][:, 0]); tr = w / w.sum()
            # the truth's own bounded-difference constant over single-torsion flips between SA patterns
            g = -eps * S["prof"][:, 0]
            both = sa[S["nb_from"]] & sa[S["nb_to"]]
            c_true = float(np.max(np.abs(g[S["nb_from"]][both] - g[S["nb_to"]][both]))) if both.any() else 0.0
            for dname, Phi in (("Rg2", S["rg2"][:, None]), ("three-shell profile", S["prof"])):
                bm = bmin(S, model, Phi, tr @ Phi)
                out.append(dict(n=n, falsification=True, eps=eps, data=dname, b_min=bm, c_true_SA=c_true))
                print(f"n={n} truth exp(+{eps} c3): data {dname:20s} certify b >= {bm:.3f}   "
                      f"(truth's max single-flip difference between self-avoiding patterns: {c_true:.3f})", flush=True)
        print(f"n={n} done in {time.time()-t0:.0f}s", flush=True)
        json.dump(out, open("envelope_scaling.json", "w"), indent=1)
