def lattice_points_in_hull(P):
    P = np.array(sorted(P), dtype=float)
    if len(P) < 5:
        return None, None, None
    try:
        hull = ConvexHull(P)
    except Exception:
        return None, None, None
    lo = P.min(axis=0).astype(int)
    hi = P.max(axis=0).astype(int)
    grid = np.array(list(itertools.product(*[range(lo[i], hi[i] + 1) for i in range(P.shape[1])])), dtype=float)
    inside = np.all(grid @ hull.equations[:, :-1].T + hull.equations[:, -1] <= 1e-7, axis=1)
    # depth of each inside point: distance to the nearest facet (Euclidean)
    depth = -(grid @ hull.equations[:, :-1].T + hull.equations[:, -1]).max(axis=1)
    return grid[inside].astype(int), depth[inside], hull.volume


