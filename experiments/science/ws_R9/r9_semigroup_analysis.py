def find_unimodular(vecs, dim, tries=200000, seed=1):
    rng = np.random.default_rng(seed)
    V = np.array(sorted(set(vecs)), dtype=np.int64)
    for _ in range(tries):
        idx = rng.choice(len(V), size=dim, replace=False)
        M = V[idx]
        d = round(np.linalg.det(M))
        if abs(d) == 1:
            # exact check
            from sympy import Matrix
            if abs(Matrix(M.tolist()).det()) == 1:
                return [tuple(int(t) for t in r) for r in M]
    return None


