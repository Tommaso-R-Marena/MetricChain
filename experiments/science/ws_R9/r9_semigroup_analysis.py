def hnf_rank_index(vecs, dim):
    """integer row reduction; returns (rank, list of pivot values, reduced basis)"""
    rows = [list(v) for v in vecs]
    basis = []
    col = 0
    piv = []
    while col < dim:
        rows = [r for r in rows if any(r)]
        cand = [r for r in rows if r[col] != 0]
        if not cand:
            col += 1
            continue
        while True:
            cand = [r for r in rows if r[col] != 0]
            if len(cand) == 1:
                break
            cand.sort(key=lambda r: abs(r[col]))
            p = cand[0]
            for r in cand[1:]:
                q = r[col] // p[col]
                for i in range(dim):
                    r[i] -= q * p[i]
        p = [r for r in rows if r[col] != 0][0]
        if p[col] < 0:
            p[:] = [-t for t in p]
        basis.append(list(p))
        piv.append(p[col])
        rows.remove(p)
        col += 1
    return len(basis), piv, basis


