#!/usr/bin/env python3
"""P9 -- assembles docs/science/workstreams/P9_REPORT.md from report_parts/NN_*.md (text) and report_parts/gen_*.md
(tables generated by mk_tables.py from the JSON files of completed runs).  Placeholders {GEN_<NAME>} in the text
parts are replaced by the content of gen_<name>.md; {NOT_CITED} by the list of files in not_cited/.
usage: python3 -B mk_tables.py && python3 -B mk_report.py"""
import os, re, glob
HERE = os.path.dirname(os.path.abspath(__file__)); PARTS = os.path.join(HERE, "report_parts")
DST = os.path.normpath(os.path.join(HERE, "..", "..", "..", "docs", "science", "workstreams", "P9_REPORT.md"))
gen = {os.path.basename(f)[4:-3].upper(): open(f).read().rstrip("\n") for f in glob.glob(os.path.join(PARTS, "gen_*.md"))}
nc = sorted(os.listdir(os.path.join(HERE, "not_cited")))
gen["NOT_CITED"] = "\n".join(f"`not_cited/{f}`" + ("," if i < len(nc) - 1 else ".") for i, f in enumerate(nc)) if nc else "(none)"
out = []
for f in sorted(glob.glob(os.path.join(PARTS, "[0-9][0-9]_*.md"))):
    t = open(f).read()
    for _ in range(4):                                   # generated parts may themselves contain placeholders
        for key, val in gen.items():
            t = t.replace("{GEN_" + key + "}", val).replace("{" + key + "}", val)
    left = re.findall(r"\{[A-Z_0-9]+\}", t)
    assert not left, (f, left)
    out.append(t.rstrip("\n") + "\n")
open(DST, "w").write("\n".join(out))
print(f"written {DST}: {sum(len(t) for t in out)} characters, {sum(t.count(chr(10)) for t in out)} lines, from {len(out)} parts")
