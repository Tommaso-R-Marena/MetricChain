#!/usr/bin/env bash
# R7: RE-RUNS of the engineering division's own code (commit a2f6dc7) at sizes this machine reaches.
# The code is exported into a throw-away work tree OUTSIDE the repository (argument 1, default: $TMPDIR/r7_eng_work);
# only logs are written into experiments/science/ws_R7/rerun_logs/.  One step per invocation:
#   bash rerun_engineering.sh <workdir> export | harper | tables | generic_entropy [nmax] | generic_cover [nmax] | tests | lattice_check [nmax] | lattice_solvers [n] | recheck [nmax] | search [n]
# (steps that use CP-SAT need OR-Tools on PYTHONPATH; see NOTES.md)
set -euo pipefail
ENG_COMMIT=a2f6dc781de05b642189a51d2ed88f94e8ed7026
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"; ROOT="$(cd "$HERE/../../.." && pwd)"
W="${1:-${TMPDIR:-/tmp}/r7_eng_work}"; STEP="${2:-export}"; LOG="$HERE/rerun_logs"; mkdir -p "$LOG"
export OMP_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1 MKL_NUM_THREADS=1
case "$STEP" in
  export)
    rm -rf "$W"; mkdir -p "$W"
    git -C "$ROOT" archive "$ENG_COMMIT" ENGINEERING.md docs/engineering docs/collaboration src/metricchain_eng experiments/eng modal_jobs tests/eng scripts | tar -x -C "$W" ;;
  harper)
    cd "$W"; cp experiments/eng/fc_uniform_cube/harper_fc_table.json "$W/harper_stored.json"
    python3 experiments/eng/fc_uniform_cube/harper_fc.py --check 2>&1 | tee "$LOG/harper_check.log"
    python3 experiments/eng/fc_uniform_cube/harper_fc.py --nmax 14 > "$LOG/harper_table.log" 2>&1
    cmp experiments/eng/fc_uniform_cube/harper_fc_table.json "$W/harper_stored.json" && echo "harper_fc_table.json regenerated byte-identical" | tee -a "$LOG/harper_check.log" ;;
  tables)
    cd "$W"
    for f in ENG-RES-0002 ENG-RES-0007 ENG-RES-0009; do python3 experiments/eng/chain_cover/make_tables.py --verify docs/collaboration/responses/engineering/$f.md; done 2>&1 | tee "$LOG/make_tables_chain.log"
    python3 experiments/eng/twolevel/make_tables.py --verify docs/collaboration/responses/engineering/ENG-RES-0008.md 2>&1 | tee "$LOG/make_tables_twolevel.log" ;;
  generic_entropy)
    cd "$W"; cp experiments/eng/chain_cover/results/generic_Sc16_entropy.json "$W/entropy_stored.json"
    python3 experiments/eng/chain_cover/generic_entropy.py --nmin 5 --nmax "${3:-12}" 2>&1 | tee "$LOG/generic_entropy.log"
    python3 - "$W" <<'PY' | tee -a "$LOG/generic_entropy.log"
import json, sys
w = sys.argv[1]
a = json.load(open(w + "/entropy_stored.json"))["rows"]; b = json.load(open(w + "/experiments/eng/chain_cover/results/generic_Sc16_entropy.json"))["rows"]
def strip(r): return {k: v for k, v in r.items() if k != "seconds"}
print("rows regenerated identical to stored (all fields but timings):", {k: strip(a[k]) == strip(b[k]) for k in sorted(a, key=int)})
PY
    ;;
  generic_cover)
    # engineering's analyse_generic (the function the Modal entry point maps) run locally at n = 5..${3:-9}
    cd "$W"; python3 - "$W" "${3:-9}" <<'PY' 2>&1 | tee "$LOG/generic_cover.log"
import json, sys, time
w, nmax = sys.argv[1], int(sys.argv[2])
sys.path.insert(0, w + "/src")
from metricchain_eng.chains.generic_analysis import analyse_generic
stored = json.load(open(w + "/experiments/eng/chain_cover/results/generic_Sc16.json"))["rows"]
for n in range(5, nmax + 1):
    t0 = time.time(); row = analyse_generic(n, cover_time_limit=300.0)
    s = stored[str(n)]
    same_head = all(row[k] == s[k] for k in ("conformations", "classes", "max_pairs_below_cutoff_per_bead"))
    marg = max(abs(row[k] - s[k]) for k in ("min_core_margin", "min_rejected_margin"))
    cells = {k: (row["cover"][k]["lower"], row["cover"][k]["upper"], row["cover"][k]["exact"]) == (s["cover"][k]["lower"], s["cover"][k]["upper"], s["cover"][k]["exact"]) for k in s["cover"]}
    tie = max(abs(row["cover"][k]["nearest_tie"] - s["cover"][k]["nearest_tie"]) for k in s["cover"])
    red = {k: row["cover"][k]["reduced"] == s["cover"][k]["reduced"] for k in s["cover"]}
    print(f"n={n}: counts identical {same_head}; margins differ by <= {marg:.1e}; cover cells identical {sum(cells.values())}/12; "
          f"reduced sizes identical {sum(red.values())}/12; nearest_tie differs by <= {tie:.1e}; {time.time()-t0:.0f} s", flush=True)
PY
    ;;
  tests)
    cd "$W"; mkdir -p build
    cc -O3 -o build/dia_enum src/metricchain_eng/chains/dia_enum.c && cc -O3 -o build/dia_flip src/metricchain_eng/chains/dia_flip.c
    python3 -m pytest tests/eng -q -x -p no:cacheprovider ${3:-} 2>&1 | tail -15 | tee "$LOG/pytest.log" ;;
  lattice_check)
    cd "$W"; mkdir -p build; cc -O3 -o build/dia_enum src/metricchain_eng/chains/dia_enum.c
    python3 experiments/eng/chain_cover/run_lattice.py --check --nmin 5 --nmax "${3:-13}" --net-time-limit 20 2>&1 | tee "$LOG/run_lattice_check.log" ;;
  lattice_solvers)
    # which solvers does the COMMITTED driver run?  (analyse_table at n = ${3:-14}; prints the stored and the regenerated "solvers" field)
    cd "$W"; python3 - "$W" "${3:-14}" <<'PY' 2>&1 | tee "$LOG/lattice_solvers.log"
import json, sys
w, n = sys.argv[1], int(sys.argv[2])
sys.path.insert(0, w + "/src")
from metricchain_eng.chains.lattice_analysis import analyse_table
from metricchain_eng.chains.profile_cover import parse_enum_output
tab = parse_enum_output(open(f"{w}/experiments/eng/chain_cover/data/dia_Sc12_n{n}.txt").read())
row = analyse_table(tab, ("highs", "cpsat"), exact_nets=False, cover_time_limit=300.0)
stored = {r["n_torsions"]: r for r in json.load(open(w + "/experiments/eng/chain_cover/results/lattice_Sc12.json"))["rows"]}[n]
for k, v in row["cover"].items():
    s = stored["cover"][k]
    print(f"n={n} {k}: regenerated N_cov={v['N_cov']} solvers={v['solvers']} lower_certified={v['lower_certified']} lower_solver={v['lower_solver']} | stored N_cov={s['N_cov']} solvers={s['solvers']} keys={sorted(s.keys())}")
PY
    ;;
  recheck)
    cd "$W"; cp experiments/eng/twolevel/results/x005_recheck.json "$W/recheck_stored.json"
    python3 experiments/eng/twolevel/recheck.py --nmax "${3:-4000}" 2>&1 | tee "$LOG/recheck_nmax${3:-4000}.log" ;;
  search)
    cd "$W"; python3 experiments/eng/twolevel/run_search.py --u 1 --n "${3:-1000}" --phi 0.5 0.8 --out "$W/search_out.json" 2>&1 | tee "$LOG/run_search.log"
    python3 - "$W" "${3:-1000}" <<'PY' | tee -a "$LOG/run_search.log"
import json, sys
w, n = sys.argv[1], int(sys.argv[2])
new = json.load(open(w + "/search_out.json")); new = new if isinstance(new, list) else new.get("cells", [new])
stored = [json.loads(l) for l in open(w + "/experiments/eng/twolevel/results/x005_cost.jsonl")]
for c in new:
    s = [r for r in stored if (r["u"], r["n"], r["phi"]) == (c["u"], c["n"], c["phi"])][0]
    na = c["n"] * c["a"]
    wn = max([c["flat"]["bottom"]["lcost"], c["flat"]["top"]["lcost"]] + [x["best_value"] for x in c["searches"]])
    ws = max([s["flat"]["bottom"]["lcost"], s["flat"]["top"]["lcost"]] + [x["best_value"] for x in s["searches"]])
    print(f"u={c['u']} n={c['n']} phi={c['phi']}: flat bottom regenerated {c['flat']['bottom']['lcost']/na:.4f} stored {s['flat']['bottom']['lcost']/na:.4f}; "
          f"worst found regenerated {wn/na:.4f} stored {ws/na:.4f}; per search regenerated - stored (ln cost): "
          f"{[round(x['best_value'] - y['best_value'], 6) for x, y in zip(c['searches'], s['searches'])]}; evaluations {[x['n_eval'] for x in c['searches']]}")
PY
    ;;
  *) echo "unknown step $STEP"; exit 2 ;;
esac
