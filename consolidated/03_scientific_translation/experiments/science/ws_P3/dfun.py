"""
P3 -- the three univariate functions through which the many-body character of GBn2/OBC2 enters,
and their derivatives up to order 4 (closed forms; float versions here, rigorous enclosures in
`encl.py`).

  tau(psi)  = tanh(P(psi)),  P = al*psi - be*psi^2 + ga*psi^3        (the rescaling of the descreening integral)
  ib(I)     = 1/B = 1/or - tau(or*I)/rad                             (inverse Born radius as a function of I)
  ell(I)    = ln B = -ln ib(I)
  h(w; r)   = 1/f_GB = (r^2 + e^w exp(-r^2 e^{-w}/4))^{-1/2},  w = ln(B_p B_q) = ell_p + ell_q
            = e^{-w/2} eta(D),  D = r^2 e^{-w}/4,  eta(D) = (4D + e^{-D})^{-1/2}
  d^k h/dw^k = e^{-w/2} eta_k(D),   eta_0 = eta,  eta_{k+1} = -eta_k/2 - D eta_k'.

Derivatives of tanh in its argument, with t = tanh, s = 1 - t^2:
  t1 = s, t2 = -2 t s, t3 = 2 s (3 t^2 - 1), t4 = 8 t s (2 - 3 t^2).
Faa di Bruno with P' = al - 2 be psi + 3 ga psi^2, P'' = -2 be + 6 ga psi, P''' = 6 ga, P'''' = 0:
  tau'    = t1 P'
  tau''   = t2 P'^2 + t1 P''
  tau'''  = t3 P'^3 + 3 t2 P' P'' + t1 P'''
  tau'''' = t4 P'^4 + 6 t3 P'^2 P'' + t2 (4 P' P''' + 3 P''^2)
"""
import numpy as np


def tau_derivs(psi, al, be, ga):
    """[tau, tau', tau'', tau''', tau''''] with respect to psi (broadcasting numpy arrays)."""
    P0 = al * psi - be * psi ** 2 + ga * psi ** 3
    P1 = al - 2.0 * be * psi + 3.0 * ga * psi ** 2
    P2 = -2.0 * be + 6.0 * ga * psi
    P3 = 6.0 * ga
    t = np.tanh(P0)
    s = 1.0 - t * t
    t1 = s
    t2 = -2.0 * t * s
    t3 = 2.0 * s * (3.0 * t * t - 1.0)
    t4 = 8.0 * t * s * (2.0 - 3.0 * t * t)
    return [t,
            t1 * P1,
            t2 * P1 ** 2 + t1 * P2,
            t3 * P1 ** 3 + 3.0 * t2 * P1 * P2 + t1 * P3,
            t4 * P1 ** 4 + 6.0 * t3 * P1 ** 2 * P2 + t2 * (4.0 * P1 * P3 + 3.0 * P2 ** 2)]


def ib_derivs(I, orr, rad, al, be, ga):
    """[ib, ib', ..., ib''''] with respect to I, ib = 1/B (nm^-1)."""
    td = tau_derivs(I * orr, al, be, ga)
    out = [1.0 / orr - td[0] / rad]
    for k in range(1, 5):
        out.append(-(orr ** k) * td[k] / rad)
    return out


def ell_derivs(I, orr, rad, al, be, ga):
    """[ell, ell', ..., ell''''] with respect to I, ell = ln B."""
    b = ib_derivs(I, orr, rad, al, be, ga)
    b0, b1, b2, b3, b4 = b
    return [-np.log(b0),
            -b1 / b0,
            -b2 / b0 + b1 ** 2 / b0 ** 2,
            -b3 / b0 + 3.0 * b1 * b2 / b0 ** 2 - 2.0 * b1 ** 3 / b0 ** 3,
            -b4 / b0 + (4.0 * b1 * b3 + 3.0 * b2 ** 2) / b0 ** 2 - 12.0 * b1 ** 2 * b2 / b0 ** 3 + 6.0 * b1 ** 4 / b0 ** 4]


# ---------------------------------------------------------------------------- eta_k(D)
# Stable representation: with E = exp(-D), u = 4D + E (u' = 4 - E > 0, u >= 1 at D = 0 ... ),
#   eta_k(D) = sum over monomials  coef * D^a * E^b * u^(-c/2),
# generated by  L(D^a E^b u^-c) = (-1/2 - a) D^a E^b u^-c + b D^(a+1) E^b u^-c
#                                 + 4c D^(a+1) E^b u^(-c-1) - c D^(a+1) E^(b+1) u^(-c-1)
# (from d/dD u^-c = -c u^(-c-1) (4 - E)).  For k >= 1 every monomial carries E^b with b >= 1, so
# nothing overflows at large D.  Keys: (a, b, c2) with c = c2/2; coefficients are exact Fractions.
from fractions import Fraction


def _L(terms):
    out = {}

    def add(key, v):
        if v != 0:
            out[key] = out.get(key, Fraction(0)) + v
    for (a, b, c2), v in terms.items():
        c = Fraction(c2, 2)
        add((a, b, c2), v * (Fraction(-1, 2) - a))
        add((a + 1, b, c2), v * b)
        add((a + 1, b, c2 + 2), v * 4 * c)
        add((a + 1, b + 1, c2 + 2), -v * c)
    return {k: v for k, v in out.items() if v != 0}


# eta_1 = L eta_0 = -u^-1/2 / 2 + (D/2) u^-3/2 (4 - E) = -(1 + D) E u^-3/2 / 2   (using u = 4D + E);
# starting the recursion from this simplified form keeps b >= 1 in every monomial of eta_k, k >= 1
# (the unsimplified form has two O(D^-1/2) monomials that cancel to O(e^-D)).
ETA_TERMS = [{(0, 0, 1): Fraction(1)}, {(0, 1, 3): Fraction(-1, 2), (1, 1, 3): Fraction(-1, 2)}]
for _k in range(4):
    ETA_TERMS.append(_L(ETA_TERMS[-1]))
assert all(b >= 1 for k in range(1, 6) for (a, b, c2) in ETA_TERMS[k])


def eta_k(k, D):
    D = np.asarray(D, dtype=float)
    E = np.exp(-D)
    u = 4.0 * D + E
    out = np.zeros(D.shape)
    for (a, b, c2), v in ETA_TERMS[k].items():
        out = out + float(v) * D ** a * E ** b * u ** (-0.5 * c2)
    return out


def h_derivs(w, r):
    """[h, dh/dw, ..., d^4h/dw^4] for h = 1/f_GB(r, e^w)."""
    D = r * r * np.exp(-w) / 4.0
    pre = np.exp(-w / 2.0)
    return [pre * eta_k(k, D) for k in range(5)]


if __name__ == "__main__":
    # self-test against numerical differentiation (mpmath)
    import mpmath as mp
    mp.mp.dps = 40
    al, be, ga, orr, rad = 0.733756, 0.506378, 0.205844, 0.15, 0.17
    f_tau = lambda x: mp.tanh(al * x - be * x ** 2 + ga * x ** 3)
    f_ib = lambda I: 1 / mp.mpf(orr) - f_tau(I * orr) / rad
    f_ell = lambda I: -mp.log(f_ib(I))
    worst = 0.0
    for I in (0.5, 3.0, 7.0, 12.0):
        a = tau_derivs(np.float64(I * orr), al, be, ga)
        b = ib_derivs(np.float64(I), orr, rad, al, be, ga)
        c = ell_derivs(np.float64(I), orr, rad, al, be, ga)
        for k in range(5):
            for val, fn, x in ((a[k], f_tau, I * orr), (b[k], f_ib, I), (c[k], f_ell, I)):
                ref = mp.diff(fn, x, k)
                worst = max(worst, abs(float(ref) - float(val)) / max(1.0, abs(float(ref))))
    for r in (0.1, 0.3, 0.8, 2.0):
        for w in (-4.0, -3.0, -2.0):
            hd = h_derivs(np.float64(w), np.float64(r))
            fn = lambda ww: (mp.mpf(r) ** 2 + mp.exp(ww) * mp.exp(-mp.mpf(r) ** 2 * mp.exp(-ww) / 4)) ** mp.mpf(-0.5)
            for k in range(5):
                ref = mp.diff(fn, w, k)
                worst = max(worst, abs(float(ref) - float(hd[k])) / max(1.0, abs(float(ref))))
    print("dfun self-test: worst relative deviation from mpmath numerical derivatives:", worst)
    for k in range(5):
        print(f"eta_{k}: {len(ETA_TERMS[k])} monomials; e.g. eta_{k}(0) = {float(eta_k(k, 0.0)):.6f}, eta_{k}(1) = {float(eta_k(k, 1.0)):.6f}, eta_{k}(60) = {float(eta_k(k, 60.0)):.3e}")
    print("eta_1 terms:", {k: str(v) for k, v in ETA_TERMS[1].items()})
