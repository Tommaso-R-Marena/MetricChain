"""ctypes front end of ``wcube_kernel.c``.

The shared library is compiled on first use with the system C compiler into the directory named by the
environment variable ``METRICCHAIN_ENG_BUILD`` or, by default, into ``build/`` at the repository root (the
convention of the other engineering kernels; that directory is git-ignored).

``enumerate_orbits`` is the exact enumeration (machine integers, range checked); the ``scan_*`` functions are
floating-point evaluations over all vertices and return candidates only: every number that is reported as a
bound is re-evaluated in ``exponents`` (see there).
"""
from __future__ import annotations

import ctypes as ct
import os
import subprocess
from dataclasses import dataclass
from pathlib import Path

import numpy as np

from .polytope import group_order, node_perm_table, weight_preserving_perms

_SRC = Path(__file__).with_name("wcube_kernel.c")
_lib = None

STATUS = {0: "complete", 1: "stopped: orbit limit", 2: "stopped: vertex limit", 3: "value range exceeded",
          4: "out of memory", 5: "internal inconsistency", 6: "bad arguments"}


def _build_dir() -> Path:
    env = os.environ.get("METRICCHAIN_ENG_BUILD")
    return Path(env) if env else _SRC.resolve().parents[3] / "build"


def load_library(rebuild: bool = False):
    """Compile (if needed) and load the kernel."""
    global _lib
    if _lib is not None and not rebuild:
        return _lib
    out = _build_dir() / "libwcube.so"
    if rebuild or not out.exists() or out.stat().st_mtime < _SRC.stat().st_mtime:
        out.parent.mkdir(parents=True, exist_ok=True)
        tmp = out.with_suffix(f".{os.getpid()}.tmp")
        subprocess.run(["cc", "-O2", "-Wall", "-Wextra", "-Werror", "-shared", "-fPIC", "-o", str(tmp), str(_SRC), "-lm"],
                       check=True)
        os.replace(tmp, out)
    lib = ct.CDLL(str(out))
    i32 = np.ctypeslib.ndpointer(dtype=np.int32, flags="C_CONTIGUOUS")
    i64 = np.ctypeslib.ndpointer(dtype=np.int64, flags="C_CONTIGUOUS")
    u8 = np.ctypeslib.ndpointer(dtype=np.uint8, flags="C_CONTIGUOUS")
    i8 = np.ctypeslib.ndpointer(dtype=np.int8, flags="C_CONTIGUOUS")
    f64 = np.ctypeslib.ndpointer(dtype=np.float64, flags="C_CONTIGUOUS")
    p64 = ct.POINTER(ct.c_int64)
    lib.wc_enumerate.argtypes = [ct.c_int, i32, ct.c_int, u8, ct.c_int64, ct.c_int64, p64, p64, p64, ct.POINTER(ct.c_int)]
    lib.wc_enumerate.restype = ct.c_int64
    lib.wc_fetch.argtypes = [ct.c_int, i32, i32, i32]
    lib.wc_fetch.restype = None
    lib.wc_free.argtypes = []
    lib.wc_free.restype = None
    lib.wc_neighbours.argtypes = [ct.c_int, i32, i32, i32, ct.c_int64]
    lib.wc_neighbours.restype = ct.c_int64
    lib.wc_canonical.argtypes = [ct.c_int, i32, ct.c_int, u8, i32, i32]
    lib.wc_canonical.restype = ct.c_int
    lib.wc_scan_kl.argtypes = [ct.c_int, ct.c_int, u8, ct.c_int64, i8, i8, f64, ct.c_double, ct.c_double, f64, ct.c_int,
                               f64, i64, i32, ct.c_double, p64, p64]
    lib.wc_scan_kl.restype = ct.c_int
    lib.wc_scan_renyi.argtypes = [ct.c_int, ct.c_int, u8, ct.c_int64, i8, i8, f64, ct.c_double, ct.c_double, ct.c_int,
                                  f64, f64, ct.c_int, f64, i64, i32, i32]
    lib.wc_scan_renyi.restype = ct.c_int
    _lib = lib
    return lib


@dataclass
class OrbitEnumeration:
    """Result of ``enumerate_orbits``.  ``reps[k]`` is the canonical member of orbit ``k`` (integer values at
    the integer weights ``wts``, value 0 = minimum at node 0), ``stab[k]`` the order of its stabiliser,
    ``deg[k]`` the number of polytope edges at it (-1 if the search stopped before it was processed)."""
    wts: tuple
    perms: tuple
    reps: np.ndarray
    stab: np.ndarray
    deg: np.ndarray
    status: int
    n_processed: int
    n_vertices: int
    total_degree: int

    @property
    def complete(self) -> bool:
        return self.status == 0

    @property
    def group_order(self) -> int:
        return group_order(len(self.wts), len(self.perms))

    @property
    def orbit_sizes(self) -> np.ndarray:
        return self.group_order // self.stab.astype(np.int64)


def enumerate_orbits(wts, perms=None, max_orbits: int = 4_000_000, max_vertices: int = 10 ** 7) -> OrbitEnumeration:
    """Exact enumeration of the vertices of the polytope with integer weights ``wts``, by orbits of the group
    generated by the weight-preserving coordinate permutations ``perms`` (default: all of them), the
    translations of the cube and ``phi -> -phi``.  Stops (``status != 0``) when more than ``max_orbits`` orbits
    or more than ``max_vertices`` vertices have been found."""
    lib = load_library()
    L = len(wts)
    n = 1 << L
    perms = tuple(weight_preserving_perms(wts) if perms is None else perms)
    table = np.ascontiguousarray(node_perm_table(L, perms))
    w = np.ascontiguousarray(wts, dtype=np.int32)
    nproc, tv, td = ct.c_int64(0), ct.c_int64(0), ct.c_int64(0)
    status = ct.c_int(0)
    try:
        nrep = lib.wc_enumerate(L, w, len(perms), table, int(max_orbits), int(max_vertices), ct.byref(nproc),
                                ct.byref(tv), ct.byref(td), ct.byref(status))
        reps = np.zeros((nrep, n), dtype=np.int32)
        stab = np.zeros(nrep, dtype=np.int32)
        deg = np.zeros(nrep, dtype=np.int32)
        if nrep:
            lib.wc_fetch(n, reps, stab, deg)
    finally:
        lib.wc_free()
    return OrbitEnumeration(tuple(int(x) for x in wts), perms, reps, stab, deg, int(status.value), int(nproc.value),
                            int(tv.value), int(td.value))


def neighbours(phi, wts, max_out: int = 1 << 16) -> np.ndarray:
    """The vertices adjacent to the vertex ``phi`` (rows normalised by the value at node 0)."""
    lib = load_library()
    L = len(wts)
    n = 1 << L
    out = np.zeros((max_out, n), dtype=np.int32)
    cnt = lib.wc_neighbours(L, np.ascontiguousarray(wts, dtype=np.int32), np.ascontiguousarray(phi, dtype=np.int32), out,
                            max_out)
    if cnt == -1:
        raise ValueError("the tight graph is not connected: not a vertex")
    if cnt < 0:
        raise ValueError("bad arguments")
    if cnt > max_out:
        return neighbours(phi, wts, max_out=int(cnt))
    return out[:cnt].copy()


def canonical(phi, wts, perms=None):
    """Canonical member of the orbit of ``phi`` and the order of its stabiliser (kernel version)."""
    lib = load_library()
    L = len(wts)
    perms = tuple(weight_preserving_perms(wts) if perms is None else perms)
    table = np.ascontiguousarray(node_perm_table(L, perms))
    out = np.zeros(1 << L, dtype=np.int32)
    stab = lib.wc_canonical(L, np.ascontiguousarray(wts, dtype=np.int32), len(perms), table,
                            np.ascontiguousarray(phi, dtype=np.int32), out)
    if stab < 0:
        raise ValueError("bad arguments")
    return tuple(int(v) for v in out), int(stab)


def scan_kl(L: int, table: np.ndarray, A: np.ndarray, B: np.ndarray, logpi: np.ndarray, u: float, us: float,
            lnQ: np.ndarray, K: int = 256, thr: float = np.inf):
    """Largest values of ``KL(pi_phi || Q)`` over all images of the stored orbit members.  Returns
    ``(values, rep indices, image indices, number above thr, number scanned)``; image index
    ``g = (eps * n + t) * nperm + k`` (``eps`` 0 for ``+``, 1 for ``-``)."""
    lib = load_library()
    n = 1 << L
    A = np.ascontiguousarray(A, dtype=np.int8)
    B = np.ascontiguousarray(B, dtype=np.int8)
    table = np.ascontiguousarray(table, dtype=np.uint8)
    val = np.zeros(K)
    rep = np.zeros(K, dtype=np.int64)
    g = np.zeros(K, dtype=np.int32)
    above, scanned = ct.c_int64(0), ct.c_int64(0)
    assert A.shape == B.shape and A.shape[1] == n
    k = lib.wc_scan_kl(L, table.shape[0], table, A.shape[0], A, B, np.ascontiguousarray(logpi, dtype=np.float64),
                       float(u), float(us), np.ascontiguousarray(lnQ, dtype=np.float64), K, val, rep, g, float(thr),
                       ct.byref(above), ct.byref(scanned))
    if k < 0:
        raise ValueError("bad arguments")
    return val[:k], rep[:k], g[:k], int(above.value), int(scanned.value)


def scan_renyi(L: int, table: np.ndarray, A: np.ndarray, B: np.ndarray, logpi: np.ndarray, u: float, us: float,
               ts: np.ndarray, pq: np.ndarray, K: int = 64):
    """For every order ``ts[j]`` the ``K`` largest values of ``-ln sum_x pi_phi(x)^t Q_j(x)^(1-t)`` over all
    images; ``pq[j, x] = pi(x)^t Q_j(x)^(1-t)``.  Returns lists ``(values, rep indices, image indices)``."""
    lib = load_library()
    n = 1 << L
    A = np.ascontiguousarray(A, dtype=np.int8)
    B = np.ascontiguousarray(B, dtype=np.int8)
    table = np.ascontiguousarray(table, dtype=np.uint8)
    ts = np.ascontiguousarray(ts, dtype=np.float64)
    pq = np.ascontiguousarray(pq, dtype=np.float64)
    T = len(ts)
    assert pq.shape == (T, n)
    val = np.zeros((T, K))
    rep = np.zeros((T, K), dtype=np.int64)
    g = np.zeros((T, K), dtype=np.int32)
    ntop = np.zeros(T, dtype=np.int32)
    rc = lib.wc_scan_renyi(L, table.shape[0], table, A.shape[0], A, B, np.ascontiguousarray(logpi, dtype=np.float64),
                           float(u), float(us), T, ts, pq, K, val, rep, g, ntop)
    if rc < 0:
        raise ValueError("bad arguments")
    return [val[j, :ntop[j]] for j in range(T)], [rep[j, :ntop[j]] for j in range(T)], [g[j, :ntop[j]] for j in range(T)]
